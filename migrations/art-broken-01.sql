-- Сломанный артефакт слетает с героя (владелец, 23.10.2026; ПРАВИЛА §8.63 п.3):
-- «Нужно, чтобы арт слетал с героя в арты — на нём сверху изображение, будто он
-- сломан, поверх накладка, и надеть не давало бы возможности. При этом там, где
-- дебафы, выскакивало бы уведомление на время — условно 5 секунд — с иконкой
-- арта и значком поломки».
--
-- Схема: таблица событий поломки — из неё плашка «Сломан: <имя>» над героем.
-- Пишут: удар (beta-raid/art-wear-hit.ts — тем же запросом, что износ и
-- снятие), рынок героев после покупки (art-repair/art-broken-sql.ts) и скрипт
-- запуска migrations/art-broken-launch.sql. Клиент показал плашку — shown_at.
--
-- Накатывать СТРОГО ДО кода: у админов механика работает сразу, и запрос удара
-- пишет в эту таблицу — без неё весь запрос удара падает и износ не
-- списывается (удар засчитан, ошибка в логе). Поведение игроков миграция НЕ
-- меняет: механику для них включает только скрипт запуска (флаг
-- settings.art_repair_open). Только добавляет; повторный накат безвреден.
-- Готово, когда есть таблица art_break_notice и индекс art_break_notice_unshown.
BEGIN;
SET LOCAL lock_timeout = '5s';

CREATE TABLE IF NOT EXISTS yuplink.art_break_notice (
  -- 'abn_<ключ удара>_<предмет>' | 'abn_hm_<лот>_<предмет>' | 'abn_launch_<предмет>':
  -- повтор того же удара, покупки или запуска не задваивает событие.
  id          text        PRIMARY KEY,
  account_id  text        NOT NULL,
  item_id     text        NOT NULL,
  template_id text,
  -- Имя и картинка — снимком на момент поломки: плашке не нужен второй запрос.
  name        text,
  image_url   text,
  -- Герой, с которого сняли (боец удара, купленный герой, при запуске — основной).
  hero_id     text,
  created_at  timestamptz NOT NULL DEFAULT now(),
  -- NULL — плашку ещё не показали; показали — время (ручка markArtBreakShown).
  shown_at    timestamptz
);

-- Непоказанные плашки аккаунта: каждый вход на карту и каждое «показано».
CREATE INDEX IF NOT EXISTS art_break_notice_unshown
  ON yuplink.art_break_notice (account_id, created_at)
  WHERE shown_at IS NULL;

COMMIT;
