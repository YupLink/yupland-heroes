-- Клейм подарка переживает слепой повтор моста.
--
-- Захват строки CAS (pending → claimed) сам по себе не идемпотентен: мост
-- повторяет запрос вслепую, и если ответ первой попытки потерялся, вторая
-- видит уже занятую строку и отвечает «подарок забран» — при том, что выдача
-- ещё не звалась. Подарок навсегда застревал бы в claimed с пустыми руками.
--
-- Метка попытки решает: повтор с тем же ключом снова получает СВОЮ строку.
ALTER TABLE yuplink.player_gift ADD COLUMN IF NOT EXISTS claim_op text;

-- Журнал фактических выдач: у энергии, паков и предметов своего ключа повтора
-- нет (add_energy и INSERT в инвентарь дедупа не знают), поэтому «выдача уже
-- начиналась» отмечаем здесь — до самой выдачи.
CREATE TABLE IF NOT EXISTS yuplink.gift_deliver_op (
  op         text PRIMARY KEY,
  gift_id    text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
