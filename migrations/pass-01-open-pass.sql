-- Вход в мешочек и сундук за энергию (владелец, 29.09.2026; ПРАВИЛА §8.23).
--
-- «Открыть» мешочек — 1 энергия, обычный или магический сундук — 1 энергия за
-- каждую занятую ячейку (пустой — даром). Заплатил — вход: пока стоишь на
-- месте (своя или соседняя клетка, откуда открыл), но не дольше 10 минут;
-- окно перечитывается сколько угодно, «Положить» и «Забрать» внутри входа
-- бесплатны. Сошёл с клетки, закрыл окно, истекло 10 минут — вход закрыт.
--
-- Только добавляет таблицу. Идемпотентно. Накатывать ДО кода: без неё окна
-- мешочка и сундуков не откроются.
SET lock_timeout = '5s';

-- target: 'lb:<id мешочка>' | 'pc:<id обычного сундука>' | 'mc:<карта>:<q>:<r>'
-- (магический — по клетке, сеть одна на владельца). pos_at — updated_at позиции
-- героя в миг открытия: позиция сменилась (шаг, портал, судно) — вход закрыт.
-- op — ключ нажатия «Открыть»: его повтор второй раз не платит. cost — сколько
-- энергии стоил вход (0 — продление живого входа или пустой сундук).
CREATE TABLE IF NOT EXISTS yuplink.raid_open_pass (
  account_id text        NOT NULL,
  target     text        NOT NULL,
  until      timestamptz NOT NULL,
  pos_at     timestamptz,
  op         text,
  cost       numeric     NOT NULL DEFAULT 0,
  at         timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (account_id, target)
);
-- Уборка протухших (при каждом открытии — своих, старше часа).
CREATE INDEX IF NOT EXISTS raid_open_pass_until ON yuplink.raid_open_pass (until);
