-- Один товар — один вид, даже если завели его дважды.
--
-- «Помидор» и «Помидоры» жили как разные предметы: у первого ключ стека
-- взялся от ПОЗИЦИИ маркета (mkt_*, у неё не был задан шаблон), у второго — от
-- шаблона справочника (cst_*). Итог: две ячейки в рюкзаке, скупка одного не
-- принимала другой, продать «не тот» помидор было нельзя.
--
-- Таблица связывает старый/побочный ключ с каноническим. Резолвер (item-alias.ts)
-- прогоняет через неё ЛЮБОЙ ключ вида, поэтому достаточно одной записи, чтобы
-- две сущности слились везде: рюкзак, витрина, скупка, оплата предметом.
CREATE TABLE IF NOT EXISTS yuplink.item_alias (
  kind     text NOT NULL,
  from_ref text NOT NULL,
  to_ref   text NOT NULL,
  note     text,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (kind, from_ref)
);
