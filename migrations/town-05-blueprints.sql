-- Шаблоны городов: состав плюс планировка, сохранённые под именем.
--
-- Владелец, 24.09.2026, после боевого прогона: «Генерация городов очень косо:
-- здание спавнится на объекты, спавнит одни и те же много зданий — кучу таверн
-- и ратуш, здание на здание. Приходилось удалять, удалять. Надо составлять
-- шаблоны городов: примерные расположения, что должно быть в городе и какие их
-- виды — условно город-подземелье, город адский. Наборы я уже сделал, их бы в
-- шаблоны, а потом просто расположение менять».
--
-- Почему таблица, а не JSON в настройках вкладки: шаблон переживает вкладку и
-- браузер, один админ собрал — другой развернул, и «адский город» не надо
-- набирать заново из четырнадцати строк состава перед каждым прогоном.
--
-- Что здесь НЕ хранится: сид, число поселений на зону и сами клетки. «Что
-- стоит и как стоит» — это шаблон, «где стоит» задаёт выделение на карте.
--
-- Номер 05, а не 04, как просили в задаче: town-04 уже занят town-stock, а
-- два одинаковых номера в упорядоченных миграциях — это спор о том, что
-- накатывать первым.
BEGIN;

CREATE TABLE IF NOT EXISTS yuplink.raid_town_blueprint (
  id         text PRIMARY KEY,
  name       text NOT NULL,
  -- ring | cross | grid | free — SETTLEMENT_LAYOUTS в settlement-types.ts.
  -- Текстом, а не enum: планировки добавляются кодом, и ALTER TYPE на каждую
  -- новую — лишний деплой базы ради одного слова.
  layout     text NOT NULL,
  -- Поперечник застройки в клетках и доля клеток под постройки (2..25, 0.05..0.8).
  size       integer NOT NULL,
  density    numeric NOT NULL,
  road_id    text,
  built      boolean NOT NULL DEFAULT true,
  town_zone  boolean NOT NULL DEFAULT true,
  -- [{buildingId, count, fill?}] — те же строки состава, что в рецепте зоны.
  slots      jsonb NOT NULL DEFAULT '[]'::jsonb,
  note       text,
  -- Кошелёк админа, который завёл шаблон; при перезаписи не меняется.
  created_by text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Список ищут по имени («адский»), а не по id.
CREATE INDEX IF NOT EXISTS raid_town_blueprint_name_idx
  ON yuplink.raid_town_blueprint (name);

COMMIT;
