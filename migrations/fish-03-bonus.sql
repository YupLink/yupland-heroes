-- База шанса поимки — настройка мира (10 %). Бонусы считаются В ПРОЦЕНТАХ ОТ
-- БАЗЫ и складываются: артефакт «+50 %» и удача 50 («+10 %») дают +60 %, то
-- есть 10 × 1,6 = 16 %.
--
-- fish_bonus_pct — сколько процентов к базе даёт надетый артефакт. 0 — ничего.
