-- Удача на рыбалке — только пока действует (владелец, 14.10.2026, вечер:
-- «зелье удачи действует только пока действует»; ПРАВИЛА §8.35 п. 6б).
--
-- Шанс заброса фиксировался при старте на весь заброс (до 60 попыток): выпил
-- зелье удачи за минуту до конца его срока — и час ловил с его бонусом. Теперь
-- у заброса ступени: с мига «at» (мс эпохи по часам базы — срок баффа удачи)
-- попытки идут с шансом «pct» — уже без истёкшего баффа. Формат —
-- [{"at": 1760450000000, "pct": 12.5}, …], по возрастанию мига, шанс только вниз
-- (lib/raid/fishChanceSteps.ts).
--
-- NULL — ступеней нет: шанс один на весь заброс (chance_pct). Так читаются и
-- все строки, начатые до выката, — их исход задним числом не меняется.
--
-- Накатывать ДО кода: чтение рыбалки (rowsSql) и старт (startSql) обращаются
-- к колонке — без неё рыбалка не читается и не начинается. Только добавляет
-- колонку без значения по умолчанию (мгновенно, без перезаписи таблицы).
