-- Соль зерна заброса (аудит 14.10, п.3; ПРАВИЛА §8.35).
--
-- Исход попыток считался от HMAC(секрет, op), где op — ключ нажатия из
-- браузера. Аккаунта и самого заброса в зерне не было: твин-разведчик видел,
-- что op дал рыбу, а сборщик бросал тот же op и ловил то же самое (и тот же
-- вид). Теперь зерно — HMAC(секрет, аккаунт:op:соль), а соль — случайная на
-- каждый заброс (gen_random_uuid() при старте, fishing-sql.startSql).
--
-- NULL — строки, начатые до выката: им зерно по-старому (только от op), и
-- исход уже идущих забросов задним числом не меняется.
--
-- Накатывать ДО кода: чтение рыбалки (readSql) и старт (startSql) обращаются
-- к колонке — без неё рыбалка не читается и не начинается. Только добавляет
-- колонку без значения по умолчанию (мгновенно, без перезаписи таблицы).
-- Идемпотентно. Чужой лок ждём не дольше 5 с — отказ, просто прогнать ещё раз.
