-- Заброс на несколько минут (владелец, 06.10.2026): раньше заброс был ровно
-- одной попыткой, и после каждой приходилось жать «Забросить» снова. Теперь
-- игрок выбирает ползунком, на сколько минут закидывает удочку (до 60), и
-- попытки идут сами — пока не выйдет время или не кончатся удочки.
--
-- plan_tries — сколько попыток заказано этим забросом. Старые строки читаются
-- как заброс на одну попытку: ровно то, чем они и были.
ALTER TABLE yuplink.raid_fishing
  ADD COLUMN IF NOT EXISTS plan_tries int NOT NULL DEFAULT 1;
