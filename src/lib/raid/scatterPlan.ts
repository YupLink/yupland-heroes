// Автораздача по карте: ЧТО просят разложить и ЧТО из этого вышло.
//
// Один договор на три стороны: панель админа его заполняет, сервер по нему
// раскладывает, отчёт возвращается той же панели. Типы живут в src/lib, а не
// рядом с серверными ручками, потому что клиент не должен тянуть за собой
// доступ к базе только ради формы плана.
//
// План описывает НАМЕРЕНИЕ («поставить 300 боссов и раздать им 5 млн Darai»),
// а не готовые объекты: конкретные шаблоны, номиналы и клетки разыгрывает
// сервер. Поэтому в плане нет ни клеток, ни id объектов.

/**
 * Наградный ФОНД группы целиком — не номинал одного объекта. Сервер разделит
 * его по объектам сам (боссам — по уровню, кучкам — жребием).
 *
 * `token` заполняется ТОЛЬКО при `kind: "token"`. Символ монеты рядом с любым
 * другим видом молча игнорируется выдачей: `{kind:"likes", token:"Darai"}`
 * выдаёт лайки, а не Darai (encounter-rewards подменяет вид только у token).
 */
export type ScatterFund = {
  kind: "token" | "likes" | "energy" | "tickets" | "resource" | "custom";
  token: string | null;
  amount: number;
  /** kind:"resource" — код ресурса счёта (wood, stone, gold…). */
  resource?: string | null;
  /** kind:"custom" — id своего товара (cst_…). */
  itemId?: string | null;
};

/** Как называется вид фонда по-русски. */
export const FUND_KIND_LABEL: Record<ScatterFund["kind"], string> = {
  token: "Токен",
  likes: "Лайки",
  tickets: "Билеты",
  energy: "Энергия",
  resource: "Ресурс",
  custom: "Товар",
};

/** Имя фонда для примечаний: токен зовём его же символом — так его знает админ. */
export const fundLabel = (f: ScatterFund): string => {
  if (f.kind === "token") return f.token ?? FUND_KIND_LABEL.token;
  if (f.kind === "resource") return f.resource ?? FUND_KIND_LABEL.resource;
  if (f.kind === "custom") return f.itemId ?? FUND_KIND_LABEL.custom;
  return FUND_KIND_LABEL[f.kind];
};

/**
 * Наименьший номинал одной кучки по виду фонда.
 *
 * У токенов это копейка: 250 USDT при номинале шаблона 0,1 обязаны лечь кучками
 * по паре центов, а не пропасть целиком — прежнее общее «не меньше 1» не
 * пропускало ни одной. Лайки, билеты и энергия дробными не выдаются: там
 * единица, и дробить её значит выдать игроку половину билета.
 */
export const pileStep = (kind: ScatterFund["kind"]): number => (kind === "token" ? 0.01 : 1);

/** Паки в награду: `count` — сколько ВСЕГО паков раздать по всей группе. */
export type ScatterPack = { packId: string; count: number };

/**
 * Артефакты в награду: редкость + сколько всего. `templateIds` — если админ
 * выбрал конкретные заготовки; пусто — берём любые активные этой редкости.
 */
export type ScatterArt = { rarity: string | null; templateIds: string[]; count: number };

/** Боссы: фонд делится по уровню, штучное разыгрывается жребием. */
export type BossPlan = {
  enabled: boolean;
  removeKilled: boolean;
  count: number;
  levelMin: number;
  levelMax: number;
  /** Уровни МЕСТНОСТИ (meta.level шаблона): боссы — только на ней; null — везде. */
  terrainLevel?: { from: number; to: number } | null;
  funds: ScatterFund[];
  packs: ScatterPack[];
  arts: ScatterArt[];
  lands: ScatterLand[];
};

/**
 * Кучки — сундуки и монетки. Отличаются только запасом HP шаблона, поэтому
 * план у них общий.
 *
 * `count: null` — «сколько получится»: сервер посчитает число кучек от фонда
 * (autoPileCount) и напишет это в примечаниях отчёта.
 *
 * `point` — «среднее значение» одной кучки: середина разброса, бросок идёт в
 * [точка/2, точка × 2]. Задана вместе с пустым `count` — число кучек считается
 * от неё и фонда; задано всё трое — берём как есть, но фонд остаётся жёстким
 * потолком. `null` — точку подбирает сам сервер, как было до неё.
 */
export type PilePlan = {
  enabled: boolean;
  removeKilled: boolean;
  count: number | null;
  point: number | null;
  funds: ScatterFund[];
  templateIds: string[];
  lands: ScatterLand[];
};

/**
 * Артефакты как ОБЪЕКТЫ карты. Своей награды им не нужно: артефакт отдаёт сам
 * себя, поэтому ни фондов, ни паков тут нет.
 */
export type ArtifactPlan = {
  enabled: boolean;
  removeKilled: boolean;
  count: number;
  rarities: string[];
  templateIds: string[];
  lands: ScatterLand[];
};

export type ScatterPlan = {
  /**
   * Сид раскладки: то же число — та же раскладка. Один жребий на весь запуск:
   * и порядок клеток (scatter-cells), и выбор шаблонов, и номиналы кучек.
   *
   * Пусто/null — прежнее поведение, свой случай на каждый запуск. Повторить
   * такую раскладку нельзя, и отчёт говорит об этом вслух: до сида админ,
   * увидев «не то», мог только раскладывать заново и надеяться.
   */
  seed?: number | null;
  boss: BossPlan;
  /**
   * ДОБЫЧА одним разделом — сундуки и монетки вместе, как просил владелец:
   * «разница только в том, что монеткам я не задаю паки и артефакты». Вид
   * каждого объекта решает его шаблон (запас HP), поэтому на карте они всё
   * равно расходятся по двум группам — снятие отработавших и отчёт устроены
   * по ним.
   *
   * Поле необязательное: план без него (старый клиент, ручной запрос)
   * по-прежнему раскладывается двумя разделами ниже.
   */
  loot?: PilePlan;
  chests: PilePlan;
  coins: PilePlan;
  artifacts: ArtifactPlan;
};

/**
 * Местности, отмеченные админом у раздела. Пусто — прежнее поведение: объект
 * встаёт на местность своего шаблона, а без неё на любую сушу. Отмечено хоть
 * одно — выбор админа местность шаблона ПЕРЕБИВАЕТ, а число объектов раздела
 * считается по местностям (см. scatterLands.landTotal), а не по полю «Сколько».
 */
/**
 * Одна отмеченная местность раздела.
 *
 * `count === null` — «своего числа нет»: такая местность делит с другими
 * такими же общее «Сколько» раздела. Ноль — это НЕ null: ноль значит «сюда не
 * класть», и молча превращать его в долю нельзя.
 *
 * Тип живёт здесь, а не рядом с арифметикой (scatterLands): та тянет отсюда
 * потолок группы, и встречный импорт замкнул бы модули в кольцо.
 */
export type ScatterLand = { terrainId: string; count: number | null };

/** Группы объектов в порядке раскладки. Тот же набор, что у scatter-apply. */
export const SCATTER_GROUPS = ["boss", "chest", "coin", "artifact"] as const;
export type ScatterGroup = (typeof SCATTER_GROUPS)[number];

/**
 * Потолок одной группы за запуск. Карта — 16 тысяч клеток; больше пяти тысяч
 * объектов за заход не раскладка, а опечатка в поле ввода.
 *
 * Живёт в общем договоре, а не у сервера: этим же числом режет себя форма и
 * упирается автосчёт кучек по фонду. Три отдельные пятёрки в трёх файлах
 * разъехались бы на первой же правке.
 */
export const MAX_PER_GROUP = 5000;

/** Потолок сида — Int32, как у генератора зон: влезает в любой JSON и в md5-строку. */
export const SCATTER_SEED_MAX = 2_147_483_647;

/** Подписи групп: один словарь на отчёт в панели и на примечания с сервера. */
export const GROUP_LABEL: Record<ScatterGroup, string> = {
  boss: "Боссы",
  chest: "Сундуки",
  coin: "Монетки",
  artifact: "Артефакты",
};

/**
 * Итог по одной группе.
 *
 * Две недостачи считаются ОТДЕЛЬНО, потому что лечатся по-разному:
 * `short` — клетки не нашлось вовсе, свободных на карте столько и есть: чинится
 * освобождением места или меньшим числом объектов;
 * `lost` — клетка была, но её перехватили между жребием и записью (игрок встал,
 * админ покрасил): чинится повтором раздачи.
 *
 * `offLand` — встали, но не на свою местность: её не хватило, и объект ушёл на
 * первую попавшуюся свободную клетку. Это часть `created`, а не отдельные
 * объекты: сумма `created + short + lost` равна заказанному числу.
 */
export type ScatterGroupReport = {
  group: ScatterGroup;
  removed: number;
  created: number;
  short: number;
  lost: number;
  offLand: number;
};

/**
 * Раздали больше, чем свободно.
 *
 * НЕ запрет и не ошибка: владелец просил не ограничивать админа минусом —
 * «админ у нас осознанный и следит за этим». Пул карты и так уходит в минус
 * свободно (map-darai-hold), поэтому дело отчёта — сказать это громко и с
 * числами, а не остановить раздачу.
 *
 * `free` — остаток ДО раздачи, `need` — сколько эта монета обещает с карты,
 * `gap` — на сколько остаток уходит в минус (need − free). Если free был
 * отрицательным ещё до нас, gap показывает всю глубину минуса, а не добавку:
 * закрывать придётся именно её.
 */
export type ScatterShortfall = {
  symbol: string;
  /** Чем меряли: пул карты (Darai) или свободный остаток кошелька. */
  source: "pool" | "wallet";
  need: number;
  free: number;
  gap: number;
};

/**
 * Отчёт целиком.
 *
 * `resources` — «на карту поступило»: по каждой валюте, паку и артефакту с
 * человеческой подписью. Считается по ФАКТИЧЕСКИ размещённому, поэтому не
 * совпадёт с планом, если клеток не хватило.
 *
 * `shortfalls` живут ОТДЕЛЬНО от notes намеренно: минус — единственное, о чём
 * админ обязан узнать до нажатия, и теряться среди примечаний про местность и
 * потолки шаблонов он не должен.
 */
export type ScatterReport = {
  /** Сид, которым разыграна ЭТА раскладка; null — сида не было, повтора не будет. */
  seed: number | null;
  groups: ScatterGroupReport[];
  resources: { label: string; amount: number }[];
  shortfalls: ScatterShortfall[];
  notes: string[];
};
