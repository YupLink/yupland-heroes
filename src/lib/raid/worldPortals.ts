// Межмировые порталы на картах игрока (Ангелина, 29.10.2026): где вход и в какой
// мир он ведёт. Обычная карта показывает только их, подробная (покупная) —
// поверх своих меток «portal» отличает межмировые по q, r.
//
// Межмировой — портал, выход которого стоит на ДРУГОЙ карте. Это не то же, что
// «задан targetMap»: targetMap — карта КОМНАТЫ сети, а не направление. Портал
// Мира строителей указывает комнату на своей же карте и ведёт в Альфу, а
// портал Альфы без targetMap мог бы вести на этаж, чей портал назначил комнату
// в Альфе. Поэтому сервер смотрит на сами выходы (portal-exits). Портал
// острова новичка ведёт в основной мир (island-exit).
//
// Общий модуль: тип ответа нужен и серверу (world-portals.ts), и телефону.
import type { WorldMapMode } from "./worldMapCodec";

export type WorldPortal = {
  /** Клетка ВХОДА на карте, где стоит герой. Выходы не отдаются никогда. */
  q: number;
  r: number;
  /** Миры назначения (название этажа), кроме текущего; хотя бы один. */
  to: string[];
  /**
   * Сеть выводит и в этот же мир: выход выбирается случайно, и «межмировой»
   * здесь — лишь один из исходов. На 29.10.2026 таких порталов нет.
   */
  alsoHere: boolean;
};

export type WorldPortalsWire = {
  /** Карта героя, к которой относятся клетки: ответ прежней карты — мимо. */
  mapId: string;
  mode: WorldMapMode;
  portals: WorldPortal[];
};
