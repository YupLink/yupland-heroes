// Лайки за боссов острова (владелец, 17.10.2026, §8.47).
//
// Корабль на верфи острова стоит как в мире — 500 лайков (Строителю 50), а у
// новичка их единицы. Поэтому боссы острова платят лайками: жирно, пока игрок
// не набрал с них первые 500, дальше — по чуть-чуть. Счёт — на аккаунт за все
// его острова: пересозданный остров не начинает его заново.

/** Сколько лайков босс острова платит «жирно» в сумме на аккаунт. */
export const ISLAND_LIKES_GOAL = 500;
/** Лайков за босса, пока цель не набрана. */
export const ISLAND_LIKES_RICH = 100;
/** Лайков за босса после цели. */
export const ISLAND_LIKES_THIN = 2;

/** Сколько дать за босса, если с боссов островов уже набрано `earned`. */
export function islandBossLikes(earned: number): number {
  const left = ISLAND_LIKES_GOAL - Math.max(0, Number(earned) || 0);
  return left > 0 ? Math.min(ISLAND_LIKES_RICH, left) : ISLAND_LIKES_THIN;
}
