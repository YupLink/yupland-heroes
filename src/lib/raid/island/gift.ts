// Подарок острова до 20.10.2026 лежал в «Подарках» (строки player_gift с
// ключом island:gift:<аккаунт>:<часть>). С 20.10 лайки, золото, энергия и паки
// — в первом сундуке (loot.ts), герой — сразу в героях (island-gift). Ключи и
// заметка остаются: по ним узнаём, кто подарок уже получал старым путём, и
// окно «Подарки» подписывает старые строки.

/** Ключ повтора подарка (player_gift.source_ref): один на аккаунт и часть. */
export const islandGiftRef = (account: string, part: "likes" | "gold" | "energy" | "hero") =>
  `island:gift:${account}:${part}`;

/** Заметка подарка — окно «Подарки» пишет «Подарок острова» на языке игрока. */
export const ISLAND_GIFT_NOTE = "island:";
