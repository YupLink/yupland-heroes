//
// Каждое событие рейда несёт карту (raidLive.RaidEvent.mapId). Событие чужого
// этажа к своей карте не прикладывается: добитый в главном мире босс гасил
// объект в тех же координатах этажа, чужой побег переписывал клетки, чужой шаг
// двигал лагерь. Правило одно для потока (сервер) и для клиента.

/** Событие другого этажа: и у события, и у смотрящего этаж известен, и они разные. */
export function foreignFloor(
  eventMap: string | null | undefined,
  mine: string | null | undefined,
): boolean {
  return !!eventMap && !!mine && eventMap !== mine;
}
