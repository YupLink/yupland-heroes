// СИЛА МАГИИ: как интеллект героя удешевляет заклинания. У заклинания есть
// цена в энергии и время восстановления (откат) — интеллект режет и то, и
// другое одним процентом. Чистый модуль: тем же правилом сервер списывает
// энергию и ставит откат, а клиент рисует цену в книге.
//
// ТЗ владельца (ребаланс 24.09): «Интеллект (1 = −0,5%): 10 = −5%, 20 = −10%
// … 100 = −50% стоимости и времени восстановления. Тут уже по достижению
// значения: 120 = −55%, 140 = −60%, 160 = −65%, 180 = −70%, 200 = −75%,
// 300 = −80%». Шкала растянута ровно вдвое против прошлой (у той было
// −50% уже на 50 интеллекта); механика та же — линейный участок и ступени.
//
// ПОЧЕМУ ступени, а не продолжение линии: после 50 скидка даётся ПО ДОСТИЖЕНИИ
// порога и между порогами стоит на месте (51..59 → 50%, 60..69 → 55%). Иначе
// линейная прямая ушла бы в бесплатные касты уже к сотне интеллекта.
//
// «Проценты тоже учитываются — считается уже по конечному значению»: скидку
// берём от ИТОГОВОГО интеллекта героя (база + уровни + артефакты + бусты), а
// применяем к ПОЛНОЙ цене и полному откату заклинания — не к каким-то
// промежуточным. Порядок здесь важен: сначала конечные числа, потом скидка.
//
// РЕАЛЬНЫЕ ЧИСЛА (500 живых героев, сверено с боевой базой 09.2026): медиана
// интеллекта 10, максимум 162, средний уровень героя 5.4. Потолок уровня — 40
// (легендарка), и на нём профильный стат даёт ровно 10 + 2*40 + 4*8 + 10*4 =
// 162: выше базой не подняться, артефакты добавляют в среднем ещё +3.
// То есть сегодня рабочая часть шкалы — линейный участок и ступени до 150
// (−70%); 200 и 300 недостижимы и лежат честным заделом. Если ступень «−80%»
// когда-нибудь сработает, значит выросли герои, а не сломалась формула.

/** Ступень: с какого интеллекта какая скидка (в процентах). */
export type SpellDiscountStep = { readonly int: number; readonly percent: number };

/** До этого значения включительно скидка линейна: 1 очко интеллекта = 0,5%. */
export const LINEAR_DISCOUNT_CAP = 100;

/** Ступени выше линейного участка. Строго по возрастанию порога. */
export const SPELL_DISCOUNT_STEPS: readonly SpellDiscountStep[] = [
  { int: 120, percent: 55 },
  { int: 140, percent: 60 },
  { int: 160, percent: 65 },
  { int: 180, percent: 70 },
  { int: 200, percent: 75 },
  { int: 300, percent: 80 },
];

/** Потолок скидки — последняя ступень. Дороже 20% от цены каст не бывает. */
export const MAX_SPELL_DISCOUNT = SPELL_DISCOUNT_STEPS[SPELL_DISCOUNT_STEPS.length - 1].percent;

/**
 * Скидка на заклинания в процентах по итоговому интеллекту.
 * Мусор (NaN, отрицательные) — это не «минус к цене», а отсутствие данных:
 * скидки нет. Дробный интеллект (бусты умеют давать дроби) округляем вниз —
 * пол-очка порог не открывает.
 */
export function spellDiscountPercent(intellect: number): number {
  const raw = Number(intellect);
  if (!Number.isFinite(raw) || raw <= 0) return 0;
  const value = Math.floor(raw);
  if (value <= LINEAR_DISCOUNT_CAP) return Math.round(value * 0.5);
  let percent = Math.round(LINEAR_DISCOUNT_CAP * 0.5);
  for (const step of SPELL_DISCOUNT_STEPS) {
    if (value >= step.int) percent = step.percent;
  }
  return percent;
}

/**
 * Цена каста в энергии с учётом интеллекта.
 *
 * Считаем в целых: base * (100 − скидка) / 100, а не base * (1 − скидка/100).
 * ПОЧЕМУ: в double 10 * 0.9 = 9.000000000000002, и округление вверх вернуло бы
 * полную десятку — скидка молча пропадала бы на круглых числах.
 *
 * Округляем ВВЕРХ и держим минимум в 1 энергию: скидка не должна превращать
 * заклинание в бесплатное, иначе энергия перестаёт быть ограничителем и книгу
 * можно кастовать бесконечно. Ноль на выходе только у заклинания, которое
 * задумано бесплатным (базовая цена 0).
 */
export function spellEnergyCost(baseCost: number, intellect: number): number {
  const raw = Number(baseCost);
  const base = Number.isFinite(raw) ? Math.max(0, Math.ceil(raw)) : 0;
  if (base <= 0) return 0;
  const left = 100 - spellDiscountPercent(intellect);
  return Math.max(1, Math.ceil((base * left) / 100));
}

/**
 * Время восстановления заклинания в минутах с учётом интеллекта.
 *
 * Округляем ВНИЗ — в пользу игрока, скидку должно быть видно, — но не ниже
 * одной минуты: нулевой откат означает спам заклинанием без пауз. Ноль
 * возвращаем только у заклинания, у которого отката нет по замыслу.
 */
export function spellCooldownMinutes(baseMinutes: number, intellect: number): number {
  const raw = Number(baseMinutes);
  const base = Number.isFinite(raw) ? Math.max(0, Math.floor(raw)) : 0;
  if (base <= 0) return 0;
  const left = 100 - spellDiscountPercent(intellect);
  return Math.max(1, Math.floor((base * left) / 100));
}
