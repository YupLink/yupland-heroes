import { QueryClient, notifyManager } from "@tanstack/react-query";
import { createSyncStoragePersister } from "@tanstack/query-sync-storage-persister";
import { persistQueryClient } from "@tanstack/react-query-persist-client";
import { persistIfChanged } from "./persistIfChanged";
import { makeFrameScheduler } from "./frameNotify";
import { refetchTypeFor } from "./queryWindows";

let client: QueryClient | null = null;
let persistInitialized = false;

export function getQueryClient(): QueryClient {
  if (!client) {
    client = new QueryClient({
      defaultOptions: {
        queries: {
          // staleTime: 60с — данные считаются «свежими» минуту, не дёргаем
          //   сервер каждые 10 секунд при ре-mount компонентов.
          // gcTime: 24ч — храним в localStorage сутки, чтобы при F5 страница
          //   рисовалась МГНОВЕННО из локалки, а в фоне обновлялась.
          staleTime: 60_000,
          gcTime: 24 * 60 * 60_000,
          refetchOnWindowFocus: false,
        },
      },
    });
    // Карта рейда — колонки по 82 тыс. чисел. Структурное разделение
    // (replaceEqualDeep) на каждое событие карты обходило их целиком (13 мс на
    // Mac, ~50 мс на телефоне) и отдавало НОВЫЙ объект колонок — индекс клеток
    // (cellIndex, WeakMap по колонкам) терялся и собирался заново ещё ~50 мс.
    // Каждая правка карты и так новый объект (PackedEdit), сравнивать нечего
    // (замер 11.10.2026: 0,1 мс и объект сохранён).
    client.setQueryDefaults(["beta-raid-map"], { structuralSharing: false });
  }

  // Persist в localStorage — только на клиенте (SSR не имеет localStorage).
  // После F5 React Query восстанавливает кэш из локалки → данные показываются
  // мгновенно, без ожидания сервера. В фоне идёт refetch свежего.
  if (!persistInitialized && typeof window !== "undefined") {
    persistInitialized = true;
    // Ответы, пришедшие до кадра, — одна перерисовка вместо нескольких
    // (lib/frameNotify; в тестах остаётся планировщик библиотеки).
    if (import.meta.env.MODE !== "test" && typeof window.requestAnimationFrame === "function") {
      notifyManager.setScheduler(makeFrameScheduler());
    }
    try {
      // persistIfChanged: сохранение зовётся на каждое событие кэша, а шаг по
      // карте рейда — это несколько записей подряд. Без фильтра каждая из них
      // гоняла в localStorage всю карту на 274 КБ; теперь пишем, только когда
      // в кэше правда что-то посвежело.
      const persister = persistIfChanged(
        createSyncStoragePersister({
          storage: window.localStorage,
          key: "yuplink-rq-cache",
          throttleTime: 1000,
        }),
      );
      persistQueryClient({
        queryClient: client,
        persister,
        maxAge: 24 * 60 * 60_000,
        // buster: смена версии разово выбрасывает уже сохранённый кэш (в т.ч.
        // старого босса, лежавшего в localStorage до этого фикса). v3: рейд-запросы
        // сменили ФОРМУ ответа (forkLinks/inHub/reward.packs-массив) — старый кэш
        // без этих полей ронял рендер (loc.forkLinks.length у undefined). Бамп
        // выбрасывает несовместимый кэш; клиент дополнительно защищён (?? []).
        // v10: ответ карты теперь ВЫРЕЗАЕТ содержимое зоны тумана, а в старом
        // суточном кэше лежит полная карта — имена, арты и meta босса.
        // v9: в словаре местности карты появился voidFog (непроходимый туман).
        // Суточный кэш без него — карта БЕЗ тумана: игрок строит маршрут через
        // void-зону, а сервер молча отказывает в шаге. Бамп выбрасывает старую.
        // v11: глухой туман переехал с типа местности на саму клетку — у клеток
        // появился признак купола, а у накрытой клетки игрока больше нет
        // terrain_id. Старый суточный кэш нарисовал бы зону обычной землёй и
        // пустил в неё маршрут: правила проходимости ищут флаг, которого в нём
        // нет вовсе.
        // v12: дороги клетки едут СТОПКОЙ слоёв (packCells.roadSets), и число в
        // колонке `road` значит теперь номер стопки, а не номер дороги. Старый
        // суточный кэш без roadSets читается по-старому, но соседний ответ уже
        // новый — на карте бы вперемешку поехали не те дороги. Бамп выбрасывает.
        // v13: слои убраны — дорога на клетке снова ОДНА, и колонка `road`
        // опять индекс в roadIds. Кэш v12 с номерами стопок прочитался бы как
        // номера дорог: на карте поехали бы чужие дороги (и чужая цена шага).
        // v14: геройские ответы сменили ФОРМУ — число слотов теперь зависит от
        // редкости (эпик и лег получили лишние карманы/руки/тело), а отряд из
        // замка убран. Суточный кэш my-hero-gear/my-heroes нарисовал бы
        // легендарному герою прежние восемь слотов — ровно тот случай «надел, а
        // плашка прежняя», который владелец ловил трижды. Бамп выбрасывает.
        // v15-best-gain: у my-hero-gear появилось поле bestGain — насколько
        // вырастут характеристики, если надеть лучшее. Без бампа суточный кэш
        // отдавал ответ без него, и кнопка первые секунды врала «уже надето
        // лучшее» там, где надеть было что.
        // v16-restore-groups: подсчёт восстановления карты сменил ФОРМУ —
        // вместо плоских boss/chests/coins пришли rows с разбивкой по валюте.
        // Суточный кэш со старым ответом ронял окно: «undefined is not an
        // object (evaluating 'e.rows[r]')» ровно при попытке восстановить.
        // v17-doors: в ответе карты появился список клеток-дверей. Суточный
        // кэш без него — карта, где маршрут снова ведёт сквозь платный
        // шлагбаум, и плата списывается посреди пути молча.
        // v22-field-pending-cell: «зреет» переехало ВНУТРЬ ячейки склада (pending
        // теперь со stackKey). Старый кэш склеил бы дробное не с той ячейкой.
        // v27-map-blob: карта переехала в IndexedDB двоичным снимком с
        // версией. Старая запись beta-raid-map в localStorage (без версии)
        // восстанавливалась как «свежая» (staleTime: Infinity) и замораживала
        // карту на всю сессию — ни дельт, ни перекачки. Бамп выбрасывает.
        // v28-potion-bag: у рюкзака появилась сумка зелий (potion у стеков,
        // potionCapacity/potionOccupied/alchemy). Суточный кэш без них рисовал
        // бы зелья в рюкзаке, а сумку — «Ячейки: undefined».
        // v29-magic-chest: у стеков рюкзака появились mob (штуки с мобов) и chest
        // (магический сундук). Суточный кэш без chest прятал бы «Поставить».
        // v30: mob → collected/movable (в сундук всё собранное, окно гасло бы).
        // v36: рыбалка — заброс на минуты (у состояния появились tries/plan) и
        // улов с долями видов. Суточный кэш со старым ответом показывал бы
        // заброс без счёта попыток, пока не перечитается.
        // v38: улучшение фишек за золото — «можно улучшить» и план автоподбора
        // отдают gold вместо tickets; суточный кэш показывал бы старую форму.
        // v40: подписки esub-07 — 4 тарифа, новый состав, blockedUntil (одна за раз).
        // v42: по одной каждого вида (esub-10) — blockedUntil только у своего тарифа;
        // v41 (апгрейд, откатан) успел осесть в кэше у части игроков.
        // v43: лицензии банка по одной каждого вида — paid стал списком.
        buster: "v43-bank-license-kinds", // v42: подписки по видам; v40: тарифы подписки; v39: износ артефактов; v38: крафт за золото; v37: способность героя; v36: рыбалка; v35: турнир — entryPrice
        dehydrateOptions: {
          shouldDehydrateQuery: (query) => {
            const k0 = Array.isArray(query.queryKey) ? query.queryKey[0] : undefined;
            // «Живые» состояния босса (boss-active/boss-list/boss-leaderboard/
            // boss-fight-session/…) НЕ персистим: иначе при заходе на экран
            // босса мелькает ПРОШЛЫЙ босс (повержен, старая неделя) из localStorage,
            // пока идёт фоновый рефетч. Без персиста — сразу спиннер → свежие данные.
            if (typeof k0 === "string" && k0.startsWith("boss")) return false;
            // session / hallway-state привязаны к КОНКРЕТНОМУ аккаунту. НЕ
            // персистим: при смене ТГ на одном устройстве иначе мелькает чужой
            // онбординг/«прихожая пройдена» из localStorage до ТГ-логина. Без
            // персиста — сразу спиннер → свежее состояние своего аккаунта.
            if (k0 === "session" || k0 === "hallway-state") return false;
            // raid-locs содержит resumeLocationId («где я») — позиционный указатель,
            // не должен переживать сессию/смену ТГ в localStorage (иначе стейл-резюм
            // на маунте до рефетча). Всегда свежий с сервера.
            if (k0 === "raid-locs") return false;
            // bank-license — живые балансы и лицензии админа (форма ответа менялась
            // 17.10: фиксированные цены, алмазы, лицензия по подписке) — всегда свежие.
            if (k0 === "bank-license") return false;
            // Излишки NEAR: в ответе BigInt — JSON его не сохраняет, и сохранение
            // всего кэша падало бы молча. Живые балансы и так незачем хранить.
            if (k0 === "surplus-balance" || k0 === "surplus-signer") return false;
            // Оплата энергии «в пути» — состояние ОДНОЙ попытки покупки, а не
            // данные. В localStorage оно переживало и перезагрузку, и TTL
            // (гидрация возвращала старую запись обратно в кэш) — 25.08 игроки
            // видели вечное «зачисляем» поверх паков. Живёт только в памяти.
            if (k0 === "energy-payment-pending") return false;
            // Раскладка чужих игроков на карте рейда. Её и так перечитывают
            // раз в минуту и живым потоком, а держать сутки в localStorage
            // незачем: сохранённая — это «кто где стоял вчера». Заодно её
            // обновления перестали будить запись всего кэша на каждый шаг.
            // Состояние рейда ["beta-raid-state"] тут НЕ исключаем: экран
            // рейда гейтит первую отрисовку на нём (stateQ.isLoading), и без
            // персиста возврат в рейд встречал бы спиннером на пару секунд.
            // От записей на каждый шаг оно молчит иначе — оптимистичный шаг
            // держит прежний updatedAt (useBetaMovement), и persistIfChanged
            // такую запись пропускает.
            if (k0 === "beta-raid-players") return false;
            // Причалы — тот же случай, но злее. Их перечитывают на КАЖДЫЙ шаг
            // по воде (useBetaMovement) и живым потоком, а сохранённый список
            // означает «где корабли стояли вчера» — он всё равно перезапросится
            // через десять секунд. Зато каждое их обновление будило запись
            // ВСЕГО кэша: карта на 274 КБ синхронно сериализовалась и синхронно
            // ложилась в localStorage — десятки миллисекунд замершего главного
            // потока на каждый гребок. Карта в персисте остаётся (мгновенная
            // отрисовка и черновик админа на ней), горячие ключи — нет.
            if (k0 === "beta-raid-ships") return false;
            // Карта живёт в IndexedDB двоичным снимком с версией (mapCache):
            // в localStorage ей не место (Int16Array в JSON — километры текста),
            // а «мгновенная отрисовка» теперь из своего кэша, не из persist.
            if (k0 === "beta-raid-map") return false;
            // Автомат казино: золото в нём — живой счёт, вчерашний снимок из
            // localStorage показывал игроку «8 золота» при 1398 на карте (13.10).
            if (k0 === "slot-state") return false;
            // Редактор внутрянки замка: клетки — рабочая копия дизайнера,
            // гидрируется ОДИН раз. Суточный снимок из localStorage подменил бы
            // свежую карту, а «Сохранить» — полная замена: стёр бы чужую работу.
            if (k0 === "castle-editor") return false;
            // Цифры «Забрать сундук» и окна сундуков (вход за энергию) — только свежие.
            if (k0 === "beta-chest-pickup" || k0 === "beta-chest-net" || k0 === "beta-plain-chest")
              return false;
            if (k0 === "beta-loot-bags") return false; // мешочки: вчерашний обзор не рисуем
            // Сжигание NFT: тысячи token_id, и вчерашний список = уже сожжённые.
            if (k0 === "burn-nfts") return false;
            // Хранилище контрактов: вчерашний «можно забрать» — уже забранные NEAR.
            if (k0 === "nft-storage") return false;
            // Остров новичка — задание одного аккаунта и шаги «прямо сейчас».
            if (k0 === "beta-raid-island") return false;
            // Поломка артефактов (§8.63 п.3): флаг — свой у каждого входа (админ/игрок),
            // плашки — очередь «ещё не показано»; вчерашний снимок всплыл бы повторно.
            if (k0 === "art-broken-on" || k0 === "art-break-notices") return false;
            // Меню входа: «новичок или уже играет» решается свежим ответом на вход.
            if (k0 === "game-start") return false;
            // Просмотр героя по id из таверны (["my-heroes","view",…], gear/backpack/
            // spellbook с "view") и источник письма о турнирах живут, пока открыто
            // окно (gcTime 0). Из localStorage вернулись бы на сутки и успехом — окно
            // нарисовало бы вчерашнего героя, письмо собралось бы со вчерашней ценой.
            if (k0 === "admin-tour-letter-source" || query.queryKey[1] === "view") return false;
            // Дефолт react-query: персистим только успешно завершённые запросы
            // (не сохраняем loading/error). Воспроизводим без импорта
            // defaultShouldDehydrateQuery — тот тянет дубль query-core и ломал tsc.
            return query.state.status === "success";
          },
        },
      });
    } catch {
      // SSR / safari private mode / quota exceeded — без кэша работает как раньше
    }
  }

  return client;
}

