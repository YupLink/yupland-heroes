// Обычный сундук — общий контракт сервера и окна (владелец, 29.09.2026).
//
// Правила владельца, дословно по смыслу:
//  1. «Сундук» — товар, как магический сундук: склад на 10 ячеек. Общей сети
//     нет — каждый сундук независимый склад.
//  2. Охрану на сундук ставить нельзя, закапывать лопатой — можно.
//  3. Хранение без срока: товары не пропадают через сутки, как в мешочке.
//  4. Бугорок из-под сундука не пропадает никогда (у мешочка — со сгоревшей
//     последней порцией). Закопан может быть и пустой сундук.
//  5. «Забрать сундук» — сундук ложится в рюкзак по всем правилам места.
//  6. Магический сундук тоже закапывается, но только без охраны; после
//     закапывания — такой же бугорок. Откопанный сундук (и магический)
//     остаётся сундуком, в мешочек не превращается.
//  7. Сундуком пользуется любой игрок: все 10 ячеек общие.
//
// Решения за владельца (29.09, ПРАВИЛА §8.22): ставят на свою или соседнюю
// клетку; класть можно всё (и купленное) — метки происхождения при вкладе
// сбрасываются, как на общей полке склада; «Забрать сундук» кладёт содержимое
// в рюкзак, сколько влезет, остальное — мешочком на клетке (§8.21); по бугорку
// не видно, сундук под ним или мешочек.
import type { LootPick } from "@/lib/magicChest";

/** Ячеек в обычном сундуке: у каждого сундука свои. */
export const PLAIN_CHEST_CELLS = 10;

/**
 * Куда ставить сундук: под себя или на соседнюю клетку. Порядок кнопок пикера:
 * верхний ряд, средний (с центром), нижний — гексы «остриём вверх».
 */
export const PLACE_DIRS: ReadonlyArray<{ dq: number; dr: number }> = [
  { dq: 0, dr: -1 },
  { dq: 1, dr: -1 },
  { dq: -1, dr: 0 },
  { dq: 0, dr: 0 },
  { dq: 1, dr: 0 },
  { dq: -1, dr: 1 },
  { dq: 0, dr: 1 },
];

/** Своя клетка или соседняя — других направлений нет. */
export const isPlaceDir = (dq: number, dr: number): boolean =>
  PLACE_DIRS.some((d) => d.dq === dq && d.dr === dr);

/** Стек в сундуке (одна строка raid_plain_chest_slot). */
export type PlainChestSlot = {
  stackKey: string;
  kind: string;
  refId: string | null;
  name: string;
  image: string | null;
  count: number;
};

/**
 * Окно сундука: что в нём и сколько ячеек занято. Содержимое — только внутри
 * оплаченного входа (open, ПРАВИЛА §8.23); без него slots пуст, а price —
 * цена «Открыть» (энергия = занятые ячейки, не меньше 1; lib/openPass).
 */
export type PlainChestView = {
  q: number;
  r: number;
  name: string;
  image: string | null;
  cells: number;
  used: number;
  slots: PlainChestSlot[];
  open?: boolean;
  price?: number;
};

/**
 * «Забрать сундук» глазами подтверждения: сундук — в рюкзак (одна ячейка),
 * содержимое — сколько влезет (taken), остальное — мешочком (bagged). sig —
 * отпечаток рюкзака и сундука: подтверждение годится ровно к этим цифрам.
 */
export type PlainPickupView = {
  fits: boolean;
  need: number;
  free: number;
  chest: { name: string; image: string | null };
  slots: PlainChestSlot[];
  taken: LootPick[];
  bagged: LootPick[];
  sig: string;
};

/** Итог «Забрать сундук»: что легло в рюкзак и что — в мешочек (его id). */
export type PlainPickupResult = { taken: LootPick[]; bagged: LootPick[]; bagId: string | null };

/**
 * Бугорок сундука в окне бугорков — id вида «cm_q_r»: сундук на клетке один.
 * Мешочек и бугорок мешочка — «lb_…».
 */
export const chestMoundId = (q: number, r: number): string => `cm_${q}_${r}`;
export const isChestMound = (id: string): boolean => id.startsWith("cm_");

/**
 * «Жить» бугорку сундука, мс: он не сгорает. Слой мешочков гасит бугорок по
 * сроку, поэтому отдаём срок заведомо дальше любой сессии (десять лет).
 */
export const CHEST_MOUND_LEFT_MS = 315_360_000_000;
