// Земля после лопаты — общий контракт сервера и карты (владелец, 02.10.2026).
//
// 1. Ямка: «где выкопали ямку, если даже ничего не было — такая штука остаётся
//    в течение часа». Любое «Копать» и «Выкопать» оставляет на клетке ямку. На
//    ямку поставили что-то (мешочек, сундук) или закопали — на клетке то, что
//    там стоит, ямку не видно («будет бугорок, как и раньше»).
//    С 31.10.2026 (ПРАВИЛА §8.24 п. 6б) ямка держит клетку: «копать ещё раз
//    ямку нельзя — будет возможность только закопать её — образовывается
//    кучка». Ямка исчезла — клетка как была: копать можно и шанс на находку
//    снова есть (владелец, 12.11.2026; до этого приз был раз в сутки). Пустая ямка закапывается в кучку — бугорок с меткой
//    DIG_EMPTY_KEY (живёт как бугорок; выкопали — пусто, снова ямка).
// 2. Мои бугорки: «где я закопал разные вещи — мои закопанные кучки — нужно
//    подсвечивать первым обзором, как шахты (на одну клетку в радиусе)».
//
// Таблица ямок — migrations/dig-01-holes.sql, правило — ПРАВИЛА §8.24 п. 6а.

/** Сколько живёт ямка от последнего копания на клетке. */
export const DIG_HOLE_MINUTES = 60;

/** Порция-метка кучки из пустой ямки: не товар, «Выкопать» её снимает. */
export const DIG_EMPTY_KEY = "dig:empty";

/** Ямка во «втором обзоре»: leftMs — сколько ей жить на момент ответа. */
export type DigHoleSpot = { q: number; r: number; leftMs: number };

/**
 * Земля для кадра: ямки («q,r») и мои бугорки («q,r») — вокруг них первый
 * обзор на клетку, как у своих шахт.
 */
export type GroundMarks = { holes: ReadonlySet<string>; mounds: readonly string[] };

export const NO_GROUND: GroundMarks = { holes: new Set<string>(), mounds: [] };
