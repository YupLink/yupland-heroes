// Ключ одного нажатия: по нему сервер отличает повтор от нового действия.
//
// Мост к базе повторяет запросы вслепую, поэтому «нажал один раз — заплатил
// один раз» держится на этом ключе, а не на честности сети.
//
// crypto.randomUUID сознательно не зовём: в Telegram-вебвью эталонного
// телефона его нет, и вызов ронял бы кнопку целиком.
export function newOpId(): string {
  const rnd = () => Math.random().toString(36).slice(2, 10);
  return `${Date.now().toString(36)}${rnd()}${rnd()}`;
}
