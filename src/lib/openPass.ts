// Цена входа «Открыть» (владелец, 29–30.09.2026; ПРАВИЛА §8.23) — одна на
// сервер (SQL списания и цена в ответе окна) и кнопку «Открыть · N⚡».
//
//  • Мешочек — 1 энергия.
//  • Сундук (обычный и магический) — занятые ячейки в миг открытия, но не
//    меньше 1: пустой — 1, три занятые — 3. У магического — ячейки сети
//    ХОЗЯИНА, и у чужого тоже.
// Каждое нажатие «Открыть» платит заново: живой вход ничего не даёт даром и не
// продлевается.

/** Цена «Открыть» мешочек. */
export const BAG_OPEN_PRICE = 1;

/** Цена «Открыть» сундук: занятые ячейки, не меньше 1. */
export const chestOpenPrice = (usedCells: number): number =>
  Math.max(1, Number.isFinite(usedCells) ? Math.ceil(usedCells) : 0);
