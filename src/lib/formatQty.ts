// Красивое количество: целые без хвоста, дробь — до двух знаков.
//
// Одно правило на «Добычу», окно склада и список «Мои склады»: дробные
// единицы (награды боссов, 0,79 Огурцов) иначе печатались бы то «0.79», то
// «0.7899999999999991» — в зависимости от того, кто вычитал.
export const formatQty = (n: number): string =>
  Number.isInteger(n) ? String(n) : String(Math.round(n * 100) / 100);
