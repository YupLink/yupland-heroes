// Билеты убраны (владелец, 20.10.2026, ПРАВИЛА §8.61): вместо них — золото.
// Всё, что раньше ДАВАЛО билеты (холд NFT, музей, рефералы, задания, боксы,
// награды карты, шахты, подарки), даёт золото: 1 билет = 100 золота.
// Всё, на что билеты ТРАТИЛИСЬ (энергопаки, паки фишек, дропы, лайки, постройки,
// порталы, университет, переселение замка, вход на турнир), стоит в золоте:
// 1 билет = 500 золота. Улучшение фишек — отдельно (lib/craftGold.ts, 1 к 300).
// Остатки билетов переведены в золото по 100 (миграция tix-gold).

/** Золота за 1 билет, который игрок раньше ПОЛУЧАЛ. */
export const TICKET_EARN_GOLD = 100;
/** Золота за 1 билет, который игрок раньше ТРАТИЛ. */
export const TICKET_SPEND_GOLD = 500;

const GOLD_DP = 1e4; // золото в журнале — 4 знака после запятой

/** Сколько золота дать вместо `tickets` билетов. */
export const goldForEarnedTickets = (tickets: number): number =>
  Math.round((Number(tickets) || 0) * TICKET_EARN_GOLD * GOLD_DP) / GOLD_DP;

/** Сколько золота взять вместо цены `tickets` билетов (вверх до целого). */
export const goldForTicketPrice = (tickets: number): number =>
  Math.ceil((Number(tickets) || 0) * TICKET_SPEND_GOLD - 1e-9);
