// «Хозяин шахт» (ПРАВИЛА §8.57: «собрано с шахт, шт.»): что из собранного
// идёт в счёт ачивки.
//
// DARAI — монета, а не штуки добычи. Гриб DARAI (бывшая DARAI-шахта, §8.65)
// даёт 10 000 DARAI в час, и счёт «1 DARAI = 1 шт.» брал мифическую (30 000)
// за три часа (жалоба игрока 22.10.2026). Владелец, 22.10: «каждые 1к дараи =
// 1 очко». Каждый сбор считается сам по себе, с округлением вниз: сбор гриба —
// целые часы по 10 000, то есть ровно 10 очков за час, остатка не бывает.
// Остальное — дерево, камень, золото, алмазы, энергия, пыль, золотой и
// алмазный грибы — как было, 1 к 1. Пересчёт прошлого — achv-fix-02.
import { mushroomKindOf } from "@/lib/mushroomKinds";

/** Сколько DARAI с шахты или гриба дают одно очко «Хозяина шахт». */
export const DARAI_PER_MINELORD_POINT = 1000;

/**
 * Сколько засчитать «Хозяину шахт» за сбор amount с клетки с настройкой cfg
 * (building_config). DARAI — очко за каждые 1 000; прочее — всё собранное.
 */
export function minelordCredit(cfg: unknown, amount: number): number {
  if (mushroomKindOf(cfg) !== "darai") return amount;
  return Math.floor(Math.max(0, amount) / DARAI_PER_MINELORD_POINT);
}
