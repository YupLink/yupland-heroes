// «Продажа рыбы»: купленная самим — «только в +» (владелец, 12.10.2026:
// «Купленную рыбу считаем, если что (но только в +)»).
//
// Ревью 12.10.2026 нашло две дыры у сравнения «эта штука продана дороже, чем
// куплена»:
//  • цена ратуши зависит от запаса, и игрок двигает её сам: купил пачкой —
//    поднял цену, сдал обратно по одной — первые штуки «дороже», а убыток
//    хвоста ничего не отнимает (очки пишутся раз и не пересчитываются). Круг в
//    минусе на наценку, а очки есть — около 5 очков за 1 золото убытка, без
//    конца; так же «раскачать» ратушу и сдать в неё рыбу из другой;
//  • полкой (сундуком, мешочком) выбирали, какая покупка уйдёт с продажей.
//
// Поэтому купленное считается по игроку целиком, отдельно по каждой валюте
// (pieceFlow.ts идёт по одному товару — значит, и по каждому виду рыбы):
//  • котёл — партии его покупок этого товара за эту валюту (цена за штуку и
//    сколько осталось), где бы штуки ни лежали (счёт, полка, сундук, мешочек):
//    какие у игрока на руках, а какие на полке, на подсчёт не влияет;
//  • штука засчитывается, только если КУПЛЕНА ДЕШЕВЛЕ цены этой продажи, и
//    каждая партия — один раз: продажа по P засчитывает не больше штук, чем
//    осталось купленного дешевле P (ревью 14.10.2026: при «дороже средней цены»
//    дешёвый запас до старта держал среднюю низко, прибыль с него давала
//    «плюс», и круги «купил по 1,20 → сдал по 1,00» засчитывались сверх того,
//    что вообще куплено дешевле: acc_FbWs… — 358 очков за четыре такие сдачи);
//  • засчитываются такие штуки, только когда игрок на купленном в плюсе:
//    выручка за проданное купленное больше, чем заплачено за ВСЁ купленное
//    (непроданное — в минус сразу при покупке, иначе дорогие штуки придержали
//    бы до конца турнира). Проданное дороже в минусе ждёт: выйдет игрок в
//    плюс — штуки засчитаются на той продаже, что вывела в плюс.
// Круг через ратушу всегда в минусе на наценку — сам по себе очков не даёт.
//
// Какая штука ушла — неизвестно (штуки одинаковые), поэтому раскладка — в
// пользу игрока, но без выдумки: с засчитанной продажей уходят самые дорогие
// из купленных дешевле её цены (дешёвые остаются для продаж подешевле), а всё,
// что уходит не в зачёт (выпито, отдано, продано до записи или за другую
// валюту, сверх купленного дешевле), — самые дорогие партии. Так очков за
// купленное ровно столько, сколько даёт лучшая честная раскладка «какая штука
// с какой продажей ушла», и не больше.
//
// Купленное до старта и до записи — тоже в котле (владелец, 14.10.2026: «да,
// засчитывай все» — купленная до старта и проданная в турнире дороже рыба
// засчитывается). Плюс же считается с мига, когда продажи игрока начинают
// засчитываться (запись, не раньше старта; bookOpen): купленное, что у него
// тогда есть, идёт в минус по своей цене, будто куплено в этот миг. Выручка и
// убытки раньше — мимо: купленная когда-то и отданная за зелья рыба навсегда
// держала бы игрока в минусе. Продажи до этого мига не засчитываются и
// «дороже» не копят (counts = false). Прибыль с запаса, проданного в турнире,
// плюс даёт, но кругам не помогает: штука круга куплена дороже своей продажи.
import type { Buy } from "@/lib/tournament/goldLots";

const EPS = 1e-9;

/** Партия купленного: цена за штуку и сколько штук ещё есть. */
type Batch = { price: number; n: number };

/**
 * Котёл игрока по одной валюте: партии по возрастанию цены; cash — выручка за
 * проданное купленное минус всё заплаченное; wait — проданное дороже, пока
 * игрок в минусе.
 */
type Purse = { lots: Batch[]; cash: number; wait: number };

/** Котлы: аккаунт + валюта → котёл. */
export type BuyBook = Map<string, Purse>;

function purse(book: BuyBook, acc: string, cur: string): Purse {
  const key = `${acc}\u0000${cur}`;
  let p = book.get(key);
  if (!p) book.set(key, (p = { lots: [], cash: 0, wait: 0 }));
  return p;
}

/** Купленное дешевле price — его штука, проданная по price, засчитывается. */
const cheaper = (b: Batch, price: number): boolean => price > b.price + EPS;

/**
 * Снять n штук из котла: сначала купленные дешевле price — от самой дорогой из
 * них, потом прочие — от самой дорогой. Вернёт, сколько снято дешевле price.
 */
function take(p: Purse, n: number, price: number): number {
  let left = n;
  let dear = 0;
  for (const pass of [true, false]) {
    for (let i = p.lots.length - 1; i >= 0 && left > EPS; i--) {
      const b = p.lots[i];
      if (pass && !cheaper(b, price)) continue;
      const k = Math.min(left, b.n);
      b.n -= k;
      left -= k;
      if (pass) dear += k;
    }
  }
  p.lots = p.lots.filter((b) => b.n > EPS);
  return dear;
}

/**
 * Плюс игрока acc (null — всех) — отсюда: купленное, что у него есть, — в минус
 * по своей цене, прежние выручка и траты — мимо.
 */
export function bookOpen(book: BuyBook, acc: string | null): void {
  for (const [key, p] of book) {
    if (acc !== null && !key.startsWith(`${acc}\u0000`)) continue;
    p.cash = -p.lots.reduce((s, b) => s + b.price * b.n, 0);
    p.wait = 0;
  }
}

/**
 * Сколько купленного acc за cur куплено дешевле price — столько купленных штук
 * продажа по price может засчитать (сразу или с выходом в плюс).
 */
export function bookDear(book: BuyBook, acc: string, cur: string, price: number): number {
  const p = book.get(`${acc}\u0000${cur}`);
  return (p?.lots ?? []).reduce((s, b) => s + (cheaper(b, price) ? b.n : 0), 0);
}

/**
 * Выйдет ли acc в плюс по купленному за cur, если выручит ещё gain (продажа
 * купленного за ту же валюту).
 */
export function bookPlus(book: BuyBook, acc: string, cur: string, gain: number): boolean {
  return (book.get(`${acc}\u0000${cur}`)?.cash ?? 0) + gain > EPS;
}

/** Игрок acc сам купил qty штук за total в валюте cur. */
export function bookBuy(book: BuyBook, acc: string, cur: string, qty: number, total: number): void {
  if (!(qty > EPS)) return;
  const p = purse(book, acc, cur);
  const price = total / qty;
  const same = p.lots.find((b) => Math.abs(b.price - price) <= EPS);
  if (same) same.n += qty;
  else {
    p.lots.push({ price, n: qty });
    p.lots.sort((x, y) => x.price - y.price);
  }
  p.cash -= total;
}

/** Купленное acc ушло не его продажей (отдал за товар, выпил, продал другой) — из котла. */
export function bookGone(book: BuyBook, acc: string, buys: readonly Buy[] | undefined): void {
  for (const b of buys ?? []) take(purse(book, acc, b.cur), b.n, -Infinity);
}

/**
 * Продажа игрока acc за валюту cur по price за штуку; buys — его купленное в
 * этой продаже; counts — продажа засчитывается (после записи и старта). Вернёт,
 * сколько купленных штук засчитать на ней (с ждавшими).
 */
export function bookSale(
  book: BuyBook,
  acc: string,
  cur: string,
  price: number,
  buys: readonly Buy[] | undefined,
  counts = true,
): number {
  let sold = false;
  for (const b of buys ?? []) {
    const p = purse(book, acc, b.cur);
    // Купленное за другую валюту и продажа до записи — не в зачёт: уходят
    // самые дорогие партии; выручка своей валюты — только за свою валюту.
    const same = b.cur === cur;
    const dear = take(p, b.n, same && counts ? price : -Infinity);
    if (!same) continue;
    sold = true;
    p.cash += price * b.n;
    p.wait += dear;
  }
  const p = purse(book, acc, cur);
  if (!counts || !sold || !(p.cash > EPS)) return 0;
  const give = p.wait;
  p.wait = 0;
  return give;
}
