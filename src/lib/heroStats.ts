/** Значение одного стата на уровне lvl. */
export function statAt(g: Growth, lvl: number): number {
  const [base, per1, per5, per10] = g;
  const l = Math.max(0, Math.floor(lvl));
  return base + per1 * l + per5 * Math.floor(l / 5) + per10 * Math.floor(l / 10);
}

export type HeroStats = Record<HeroStatKey, number>;

/**
 * Запасная специализация, когда раса известна, а спеца нет или он не из таблицы.
 *
 * Инцидент 15.09.2026: два common-шаблона («An — Sad Face», «Fedr - Stubborn
 * Mage») завели с расой и прочерком вместо спеца — форма это позволяла, сервер
 * не проверял. Строки «без спеца» в RACE_STATS нет, и 70 героев докачали до
 * 15 ур. с нулями во всех шести графах («баг на комонках»). Воин — нейтральная
 * линейка без перекоса в один стат. Это аварийный запас, а не норма: в базу
 * такое больше не пишется (server/api/items-hero-guard).
 */
export const FALLBACK_SPEC = "Воин";

/** Спец, по которому реально считаем: свой, если он в таблице, иначе запасной. null — расы нет. */
export function resolveSpec(race: string | null, spec: string | null): string | null {
  const byRace = race ? RACE_STATS[race] : undefined;
  if (!byRace) return null;
  return spec && byRace[spec] ? spec : FALLBACK_SPEC;
}

// Предупреждение один раз на пару раса|спец за процесс: heroStatsAt зовут на
// каждый список героев, и без дедупа лог забился бы одной и той же строкой.
const warned = new Set<string>();

/** Все шесть характеристик героя на уровне lvl. Неизвестная раса → нули; нет спеца → FALLBACK_SPEC. */
export function heroStatsAt(race: string | null, spec: string | null, lvl: number): HeroStats {
  const used = resolveSpec(race, spec);
  if (used && used !== spec) {
    const key = `${race}|${spec ?? ""}`;
    if (!warned.has(key)) {
      warned.add(key);
      const msg = `у расы «${race}» спец «${spec ?? "—"}» не из таблицы — считаю как ${used}`;
      console.warn(`[heroStats] ${msg}`);
    }
  }
  const block = race && used ? RACE_STATS[race]?.[used] : undefined;
  const out = {} as HeroStats;
  for (const k of HERO_STAT_KEYS) out[k] = block ? statAt(block[k], lvl) : 0;
  return out;
}
