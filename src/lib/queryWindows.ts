// Окна «у клетки»: карточка цели и склад. Их ответ привязан к месту — сервер
// отказывает, когда игрок отошёл («Объект не найден», «Сначала подойди к
// складу»). Такие ключи после мутаций перечитываем только ОТКРЫТЫМИ: закрытые
// копии живут в кэше сутки (gcTime), и refetchType "all" будил их все разом —
// на 02.10 это ~36 запросов карточек на один удар, 89 % с ошибкой, и 81 %
// ошибок у склада. Закрытая копия после инвалидации помечена устаревшей и
// перечитается сама, когда окно откроют снова.
// Склад замка отвечает только у замка — на карте закрытую копию будить нельзя.
const LOCATION_WINDOWS = new Set(["beta-encounter", "beta-warehouse", "castle-warehouse"]);
// Тяжёлые окна героя: снаряжение — 152 КБ, предметы — сотни. Закрытые копии
// после каждого удара и рубки перечитывались в фоне (14.10.2026: ~0,8 раза в
// минуту даже в покое, 143 МБ за 3 часа) — разбор на телефоне в главном
// потоке. Устаревшую копию окно перечитает само, когда его откроют.
const HEAVY_WINDOWS = new Set(["my-hero-gear", "my-game-items"]);

export const refetchTypeFor = (key: string): "active" | "all" =>
  LOCATION_WINDOWS.has(key) || HEAVY_WINDOWS.has(key) ? "active" : "all";
