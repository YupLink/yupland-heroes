// Правила корабля — общие для сервера и карты.
//
// Сев на корабль, игрок управляет им как героем: фигурка героя исчезает, по
// воде двигается само судно. Плавание стоит одинаково на любой воде, а вот
// сход на берег — по цене той клетки, на которую сходишь.
//
// Обе цены живут ЗДЕСЬ и только здесь: клиент рисует их на клетках и на
// кнопке, сервер по ним списывает. Разъедутся числа — игрок увидит одно, а
// заплатит другое.
import { scaleEnergy } from "@/lib/raid/island/energy";

/** Посадка на корабль: забраться на борт стоит как гребок по воде. */
export const SHIP_BOARD_ENERGY = 3;

/** Шаг по воде на обычном корабле — не зависит от типа воды. */
export const SHIP_STEP_ENERGY = 3;

/** Шаг по воде на БОЛЬШОМ корабле — дешевле обычного (заказ владельца). */
export const SHIP_STEP_ENERGY_BIG = 2;

/**
 * Пороги тира верфи (тир 0-индексный: `isBuilt` — это `tier >= tiersCount-1`).
 * Обычный корабль — со 2-го тира (индекс 1), большой — с 3-го (индекс 2).
 * Пороги, а НЕ isBuilt: добавили админу 3-й тир — обычный корабль обязан
 * остаться доступным на 2-м, иначе апгрейд верфи ломал бы прежнюю механику.
 */
export const SHIPYARD_TIER_SMALL = 1;
export const SHIPYARD_TIER_BIG = 2;

/** Цена большого корабля: дерево + товар. Рас/специализаций не смотрит. */
export const BIG_SHIP_WOOD = 10;
/** Товар в цене большого корабля — по названию (ключ рюкзака ищем в БД). */
export const BIG_SHIP_ITEM_NAME = "Молоток";

/**
 * Потолок скидки за скорость: −99%. Саму скидку даёт таблица скорости
 * (heroPowerCurve.SPEED_DISCOUNT: 100 → 50%, 200 → 75%, 400 → 95%, 500 → 99%),
 * здесь только зажим. Сотни процентов не бывает — бесплатной ходьбы нет.
 */
export const HERO_STEP_DISCOUNT_MAX_PCT = 99;

/**
 * Вода ли это — по названию типа местности. Тот же признак использует SQL
 * (server/api/beta-raid/ships.ts): если местность переименуют, перестанут
 * работать оба.
 */
// «ocean» тоже здесь: океан обязан быть ПОДМНОЖЕСТВОМ воды, иначе клетка,
// названная по-английски «Ocean», проходила бы как вода-для-океана, но не как
// вода вообще — и сервер пускал бы на неё пешком (см. WATER_SQL, тот же список).
const WATER_RE = /(вод|water|море|океан|ocean|river|река)/i;

export function isWaterName(name: string | null | undefined): boolean {
  return WATER_RE.test(name ?? "");
}

/**
 * Океан — ГЛУБОКАЯ вода: тоже вода (WATER_RE ловит «океан»), но обычному
 * кораблю в неё нельзя, ходит только большой. Отличаем по названию, как и саму
 * воду; тот же признак дублирует SQL (cell-sql.OCEAN_SQL).
 */
const OCEAN_RE = /(океан|ocean)/i;

export function isOceanName(name: string | null | undefined): boolean {
  return OCEAN_RE.test(name ?? "");
}

/**
 * Множитель хода. Число — один на всё (остров новичка 0,1, мир 1). Пара — погода
 * карты (владелец, 26.10.2026): ход героя (суша, сход на берег) × step, ход судна
 * (посадка и гребок — «идёт судно, а не герой») × ship; уже вместе с множителем карты.
 */
export type MoveMult = number | { step: number; ship: number };

/** Множитель ветки хода: судно (посадка, гребок) или ноги. */
export const moveMultFor = (m: MoveMult | undefined, ship: boolean): number =>
  m == null ? 1 : typeof m === "number" ? m : ship ? m.ship : m.step;

/** Множитель карты × погода; погода не влияет (оба 1) — прежнее число. */
export function moveMultOf(mapMult: number, w?: { step: number; ship: number } | null): MoveMult {
  const step = Number.isFinite(w?.step) ? Number(w?.step) : 1;
  const ship = Number.isFinite(w?.ship) ? Number(w?.ship) : 1;
  if (step === 1 && ship === 1) return mapMult;
  return { step: mapMult * step, ship: mapMult * ship };
}

/** Одинаковые множители (кэш цен маршрута сравнивает по числам). */
export const sameMoveMult = (a: MoveMult, b: MoveMult): boolean =>
  moveMultFor(a, false) === moveMultFor(b, false) && moveMultFor(a, true) === moveMultFor(b, true);

/**
 * Цена ОДНОГО хода — единственная формула на клиент и сервер.
 *
 * Замедление дорожит любой ход: и шаг по суше, и гребок по воде, и посадку на
 * борт. Раньше кнопка в окне корабля считала посадку без надбавки, и
 * замедление обходилось через окно: на клетке было написано одно, списывалось
 * другое. Теперь и карта, и кнопка, и сервер зовут отсюда.
 *
 * Правило владельца 27.09: шаг ногами (по суше и сход на берег) стоит
 *   (цена клетки + замедление) × (1 − скидка скорости).
 * Скидка режет и надбавку замедления: быстрый герой проходит дебафф легче.
 * Было с 26.08: цена клетки × (1 − скидка) + замедление плоско — герой с −98%
 * на клетке 1 под замедлением 2 платил 2.02, теперь 0.06.
 *
 * Посадка и гребок скидке не поддаются: там идёт судно, а не герой. Для них
 * надбавка по-прежнему плоская — база + замедление.
 *
 * Скидка процентная и умножающая, по таблице скорости (SPEED_DISCOUNT). Цена
 * бывает дробной (клетка 1 при −65% — 0.35): энергия numeric, ей по силам.
 */
export function stepEnergyCost(opts: {
  /** Шаг на свободное судно — это посадка, стоит фиксированно. */
  boarding?: boolean;
  /** Плывём по воде на борту — гребок не зависит от типа воды. */
  sailing?: boolean;
  /** На борту БОЛЬШОГО корабля: гребок дешевле (посадка — как у всех). */
  bigShip?: boolean;
  /** Цена самой клетки (дорога или местность) — шаг по суше и сход на берег. */
  cellCost?: number;
  /** Надбавка замедления, пока эффект висит. */
  slowExtra?: number;
  /** Скидка героя за скорость, в ПРОЦЕНТАХ. Нет героя — нет поля. */
  heroStepDiscountPct?: number;
  /**
   * Множитель карты (energyMultOf): остров — 0,1, мир — 1 (по умолчанию); с погодой —
   * пара (MoveMult): ноги × step, посадка и гребок × ship.
   */
  mult?: MoveMult;
}): number {
  // Множитель — один раз к ИТОГУ хода (после скорости и замедления), тем же
  // scaleEnergy, что и все цены острова: до сотых, платное не дешевле 0,01. При
  // множителе 1 — число как было.
  const ship = !!(opts.boarding || opts.sailing);
  return scaleEnergy(baseStepCost(opts), moveMultFor(opts.mult, ship));
}

function baseStepCost(opts: Parameters<typeof stepEnergyCost>[0]): number {
  const slow = Math.max(0, opts.slowExtra ?? 0);
  // Два знака после запятой — ровно та точность, с которой энергия живёт в
  // базе (ROUND(..., 2) внутри touch_energy_atomic). Без округления клиент
  // показывал бы 0.35000000000000003, а сервер списывал бы своё.
  if (opts.boarding || opts.sailing) {
    const base = opts.boarding
      ? SHIP_BOARD_ENERGY
      : opts.bigShip
        ? SHIP_STEP_ENERGY_BIG
        : SHIP_STEP_ENERGY;
    return round2(base + slow);
  }
  return round2(landStepCost(opts.cellCost ?? 1, slow, opts.heroStepDiscountPct));
}

/**
 * Шаг ногами: (клетка + замедление) × (1 − скидка). Пол в одну сотую энергии:
 * на карте есть местность дешевле единицы (небеса 0.1, магическая земля 0.2),
 * и −99% превращали бы её в 0.001 — то есть в бесплатную ходьбу после
 * округления до копейки, которой живёт энергия в базе. Даром не ходят даже
 * очень быстрые. Клетка «даром» без замедления так и остаётся даром.
 */
const landStepCost = (cellCost: number, slow: number, pct: number | undefined): number => {
  const full = Math.max(0, cellCost) + slow;
  return full > 0 ? Math.max(0.01, full * (1 - heroStepDiscountRate(pct))) : 0;
};

/** Скидка в долях (0…0.99): один зажим на клиент и сервер. */
export function heroStepDiscountRate(pct: number | undefined): number {
  const p = Math.max(0, Math.min(HERO_STEP_DISCOUNT_MAX_PCT, Number(pct) || 0));
  return p / 100;
}

const round2 = (n: number): number => Math.round(n * 100) / 100;

/**
 * Как печатать цену хода — один формат на все три места: кружок на клетке,
 * метка маршрута и кнопка посадки в окне корабля.
 *
 * Энергия numeric, поэтому цены бывают дробными. Раньше кружок печатал 2.5, а
 * метка маршрута — 2.5000000000000004: одно и то же число выглядело по-разному
 * в двух сантиметрах друг от друга. Формат живёт рядом с формулой: меняется
 * цена — меняется и подпись, без обхода трёх файлов.
 *
 * Два знака, а не один: процентная скидка героя даёт цены вроде 0.35, и
 * округление до десятых печатало бы 0.4 — на четверть дороже списанного.
 */
export function formatEnergyCost(cost: number): string {
  // Округляем ДО проверки на целое: 0.1 + 0.2 иначе печатается как
  // 0.30000000000000004 и не проходит проверку «целое ли».
  const rounded = round2(cost);
  if (Number.isInteger(rounded)) return String(rounded);
  // Хвостовой ноль не печатаем: 0.5, а не 0.50.
  return String(rounded);
}
