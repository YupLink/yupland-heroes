// Кубик с сидом для тестов.
//
// Раздача наград — это броски, и без воспроизводимого генератора упавший тест
// нельзя ни повторить, ни разобрать: «иногда сумма больше фонда» — не отчёт.
// mulberry32 выбран за короткость: качество распределения тут вторично,
// повторяемость — единственное требование.
export type Rnd = () => number;

export function seeded(seed: number): Rnd {
  let s = seed >>> 0;
  return () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = Math.imul(s ^ (s >>> 15), 1 | s);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
