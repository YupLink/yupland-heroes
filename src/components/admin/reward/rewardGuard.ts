// Сторож сохранения фонда наград: не пускать недоукомплектованную строку.
//
// fromDraftCfg такие строки ФИЛЬТРУЕТ — и делает это правильно: до раздачи
// награда без кода ресурса или без шаблона товара доехала бы вечной заявкой в
// очереди. Плохо было другое: форма всё равно говорила «Сохранено», и админ,
// вписавший 1000 и не выбравший вид ресурса, узнавал о пропаже настройки
// только на следующем открытии.
//
// Отдельный файл от rewardDraft.ts нарочно: тот чистый (его гоняют тесты), а
// здесь живёт тост — и значит sonner.
import { toast } from "sonner";
import { draftProblems, type DraftConfig } from "./rewardDraft";

/**
 * true — фонд можно сохранять. false — сохранять нечего и админу уже сказано,
 * чего не хватает. Зовётся ПЕРЕД fromDraftCfg на каждой кнопке сохранения.
 */
export function rewardDraftReady(cfg: DraftConfig): boolean {
  const bad = draftProblems(cfg);
  if (bad.length === 0) return true;
  toast.error(`Не сохранено: в фонде наград ${bad.join(", ")}. Дозаполни строку или удали её.`);
  return false;
}
