// Сторожа тумана при смене этажа (накладка миров, 07.10.2026).
//
// Маска разведанного привязана к сетке карты. В кадр перехода порталом карта
// уже новая, а маска ещё прежняя — синхронизация отправляла всё разведанное
// прежнего этажа как разведанное нового и вливала пришедшее в прежний.

/**
 * Маска собрана под эту карту (этаж) — иначе (кадр смены этажа) она чужая: null.
 *
 * Сверяем КАРТУ, а не объект сетки: сетка пересоздаётся на каждую правку карты
 * (чужой шаг, удар, побег — раз в секунду), и сверка по объекту на этот кадр
 * выбрасывала всё разведанное — карта мигала туманом, миникарта гасла на
 * 0,4 с (07.10.2026). Новая сетка той же карты маске подходит: её перекладывает
 * rebind в useFogOfWar.
 */
export function fogOfMap<T>(
  seen: T | null,
  maskMapId: string | null,
  mapId: string | null,
): T | null {
  return seen && mapId && maskMapId === mapId ? seen : null;
}

/**
 * Сервер этаж не помнит вовсе (total 0 на сверке), а устройство помнит
 * отправленное — разведанное на сервере сброшено, память устройства устарела.
 * total не число (подсчёт не удался) — не знаем, ничего не сбрасываем.
 */
export function serverForgot(since: string | undefined, total: unknown, pushed: number): boolean {
  return !!since && total === 0 && pushed > 0;
}
