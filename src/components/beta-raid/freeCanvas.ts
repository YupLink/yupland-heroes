// Память холста отдаём сразу, а не когда до него дойдёт сборщик мусора.
//
// Брошенный канвас держит свой буфер (обычно — в памяти графики) до сборки
// мусора, а она на телефоне приходит позже, чем кончается память графики
// Telegram-вебвью. Тогда вебвью начинает терять слои: серые прямоугольники
// вместо панелей, чёрная карта, мигание (видео владельца 23.10.2026).
// Нулевой размер освобождает буфер в тот же момент.
export function freeCanvas(cv: HTMLCanvasElement | null | undefined): void {
  if (!cv) return;
  cv.width = 0;
  cv.height = 0;
}
