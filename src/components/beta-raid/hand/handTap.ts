// Что делает тап по карте с вещью в руке (владелец, 26.10.2026: «герой ходит как и
// прежде… нажатие + кнопка разместить; 2 раза нажать = разместить; переключатель
// „тап = размещение“, умный»). Ход героя рука не отнимает никогда:
//
//  · клетка дальше круга, нельзя или своя — обычный тап (ход, бой, постройка);
//  · двойной тап по годной клетке — сделать сразу (отмеченные и эту); динамит — только
//    по тому, что взорвётся;
//  · у тапа нет другого смысла — клетку берёт рука: земля в пустоту (туда не ходят),
//    динамит по тому, что взорвётся (шахта, цель, дерево или гора). Отметить или снять
//    отметку — кнопка внизу; с «тап = разместить» эта клетка ложится сразу. Переключатель
//    умный: трогает только пустоту — по земле тап по-прежнему ведёт героя. Вода в круге —
//    цель красного (рыба, 30.10.2026): тап и двойной тап — как по дереву;
//    Вода под землю — тоже рука (тестер, 26.10.2026: «хочу землю на воду, а пишет „нет
//    корабля“»): без корабля по ней не ходят;
//  · у тапа есть свой смысл (своя земля под перестройку, пустая земля под динамит) —
//    обычный тап, а на плашке маршрута ещё кнопка руки для этой клетки;
//  · жила (29.10) ложится на обычную землю, по которой ходят: тап — ход и кнопка на
//    плашке, двойной — сразу (отмеченные и эту), «тап = разместить» — сразу эту.
//    Переключатель и тут умный: берёт только клетку, что держит жилу (зелёную), —
//    по остальным тап ведёт героя. Гриб (31.10) — так же: сажают рядом с героем на землю,
//    по которой ходят.
import { dynamiteKindOf } from "@/lib/dynamite";
import { getHand, handAt, type Hand, type HandCell } from "./handStore";

/** now — эта клетка и все отмеченные (двойной тап); one — только эта («тап = разместить»). */
export type HandTapPlan =
  | { do: "pass" }
  | { do: "offer" }
  | { do: "mark" }
  | { do: "now" }
  | { do: "one" };

/** Клетку берёт рука целиком: у тапа по ней нет другого смысла. Жила — никогда: под ней земля. */
export const handTakes = (hand: Pick<Hand, "kind">, c: HandCell): boolean =>
  c.ok && (hand.kind === "land" ? c.cost === 0 : hand.kind === "dynamite" ? c.hit !== null : false);

/** Тап сюда возьмёт рука (пустота мира строителей, цель динамита) — пропустить мимо тумана. */
export function handTakesAt(q: number, r: number): boolean {
  const h = getHand();
  const c = handAt(q, r);
  return !!h && !!c && handTakes(h, c);
}

export function handTapPlan(
  hand: Pick<Hand, "kind"> | null,
  c: HandCell | null,
  /** water — клетка воды: земле перестраивать её больше нечем, кроме руки. */
  o: { double: boolean; quick: boolean; water?: boolean },
): HandTapPlan {
  if (!hand || !c || !c.ok || (c.dq === 0 && c.dr === 0)) return { do: "pass" };
  // Жила — по земле, где ходят: «тап = разместить» тратил бы купленную жилу на каждый шаг
  // (переключатель общий с землёй). Только кнопка или двойной тап.
  if (hand.kind === "vein" || hand.kind === "mushroom") return { do: o.double ? "now" : "offer" };
  const takes = handTakes(hand, c) || (hand.kind === "land" && !!o.water);
  // Динамит по пустой земле двойным тапом не бросаем: дрогнул палец — минус 100 энергии.
  if (o.double && (takes || hand.kind === "land")) return { do: "now" };
  if (!takes) return { do: "offer" };
  return hand.kind === "land" && o.quick ? { do: "one" } : { do: "mark" };
}

/**
 * Красный динамит по чужому кораблю в круге броска (жалоба 28.10.2026: «динамит не
 * действует на корабль — пишет „занят другим игроком“»): корабли взрывает только
 * синий (§8.75а), а тап уходил в посадку. Теперь — подсказка вместо посадки.
 * Свой корабль — обычный тап (сесть). Клетка — цель красного (вода с рыбой, моб) —
 * тап берёт рука: корабль взрыв не тронет, а рыбу поймает.
 */
export const redOnForeignShip = (
  hand: Pick<Hand, "kind" | "stackKey"> | null,
  c: HandCell | null,
  ship: { mine: boolean } | null | undefined,
): boolean =>
  !!hand &&
  hand.kind === "dynamite" &&
  dynamiteKindOf(hand.stackKey) === "red" &&
  !!c &&
  c.hit === null &&
  !!ship &&
  !ship.mine;

/**
 * Корабль под синим динамитом — по живому списку причалов, а не по кругу броска
 * (жалоба 28.10.2026: «синий динамит не действует на корабль — „занят другим
 * игроком“»). Круг целей сервер считает, когда герой встал; корабль с экипажем
 * плывёт, и к тапу круг ещё не знал, что он здесь, — тап уходил в посадку. Список
 * причалов обновляется живым потоком на каждый гребок: приплыл — цель, уплыл — нет.
 * Свой корабль (круг пометил ownShip) целью не становится: синий его не тронет
 * (владелец, 30.10.2026), а сто энергии ушли бы впустую.
 */
export function withLiveShip(
  hand: Pick<Hand, "kind" | "stackKey"> | null,
  c: HandCell | null,
  ship: object | null | undefined,
): HandCell | null {
  if (
    !hand ||
    !c ||
    !c.ok ||
    hand.kind !== "dynamite" ||
    dynamiteKindOf(hand.stackKey) !== "blue"
  ) {
    return c;
  }
  if (ship && c.hit === null && !c.ownShip) return { ...c, hit: "ship" };
  if (!ship && c.hit === "ship") return { ...c, hit: null };
  return c;
}

/**
 * Синий в руке, чужой занятый (или разбитый) корабль за кругом броска: сесть в него
 * нельзя, тап писал «Занят другим игроком». Говорим про дальность динамита.
 */
export const blueShipTooFar = (
  hand: Pick<Hand, "kind" | "stackKey"> | null,
  c: HandCell | null,
  ship: { mine: boolean; free: number } | null | undefined,
): boolean =>
  !!hand &&
  hand.kind === "dynamite" &&
  dynamiteKindOf(hand.stackKey) === "blue" &&
  !c &&
  !!ship &&
  !ship.mine &&
  ship.free <= 0;

