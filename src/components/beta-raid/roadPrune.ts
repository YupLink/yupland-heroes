// Дорога идёт линией: у клетки две стороны, а не три (владелец, 09.10.2026 —
// «такие соединения делать только 2 стороны без 3»).
//
// Ступенька дороги по гексам даёт треугольник: клетки A–B–C идут подряд, но A и
// C тоже соседи — и лента рисует третью сторону A–C, «срезку» мимо B. Срезку
// убираем: у неё оба конца — развилки (3+ стороны), а общий сосед B — звено
// линии ровно с двумя сторонами. Настоящие развилки (без треугольника)
// остаются. Решение зависит только от исходных масок, поэтому обе клетки
// срезки убирают её одинаково и половинки ленты не расходятся.

const sides = (mask: number): number => {
  let c = 0;
  for (let m = mask; m; m &= m - 1) c++;
  return c;
};

/**
 * Маска клетки без срезок. `raw` — все соседи с той же дорогой, `rawAt(d)` —
 * такая же исходная маска соседа в направлении d (порядок ROAD_DIRS).
 */
export function pruneRoadMask(raw: number, rawAt: (d: number) => number): number {
  if (sides(raw) < 3) return raw;
  let out = raw;
  for (let d = 0; d < 6; d++) {
    if ((raw & (1 << d)) === 0 || sides(rawAt(d)) < 3) continue;
    for (const z of [(d + 5) % 6, (d + 1) % 6]) {
      if ((raw & (1 << z)) !== 0 && sides(rawAt(z)) === 2) {
        out &= ~(1 << d);
        break;
      }
    }
  }
  return out;
}
