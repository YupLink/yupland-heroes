// Картинка охранника шахты/сундука в кэше карты — по АДРЕСУ картинки, а не по
// клетке (21.10.2026). Ключ по клетке переживал смену охранника: игрок добил
// чужого, поставил своего — вблизи рисовался новый, а при отдалении спрайт
// под зум (spriteCache, мастера не вытесняются) отдавал убитого.
// Видов охраны ~8 на ~200 шахт — по адресу их и качать меньше.
export const GUARD_IMG_PREFIX = "mg:";

/** Ключ картинки охранника в кэше картинок карты (useImageCache). */
export function guardImageKey(image: string): string {
  return GUARD_IMG_PREFIX + image;
}
