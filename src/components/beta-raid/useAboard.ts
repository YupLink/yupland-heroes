// На борту ли игрок прямо сейчас.
//
// Правило одно: за штурвалом тот, кого капитаном назвал СЕРВЕР. Судно приходит
// в списке причалов с признаком `mine` — его и спрашиваем про клетку под
// ногами. Ничего не выводим из координат и ничего не дорисовываем.
//
// Раньше здесь стояло «стою на воде — значит на судне», а недостающий корабль
// хук выдумывал сам: рисовал его под героем и стирал настоящий. Из-за этого
// брошенное у берега судно пропадало с карты и «переезжало» под игрока через
// всю сушу — тот проходил пешком несколько клеток, а лодка ехала с ним под
// мышкой. Ноги у лодки не отрастают: судно живёт там, где его оставили.
//
// Свой шаг по-прежнему виден сразу, не дожидаясь сервера, но честно: плывущий,
// сходящий на берег и садящийся на борт правят кэш причалов теми же дельтами,
// что шлёт сервер (useBetaMovement + patchShipsCache). Судно двигается только
// по воде и только вместе с капитаном.
//
// Списка нет вовсе (не загрузился, оборвалась сеть) — считаем, что не на борту:
// пока клиент не знает, где флот, планировать морские маршруты ему не по чему.
import type { ShipMark } from "./drawShips";

export function useAboard(
  ships: Map<string, ShipMark>,
  playerPos: { q: number; r: number } | null,
): boolean {
  if (!playerPos) return false;
  return ships.get(`${playerPos.q},${playerPos.r}`)?.mine === true;
}
