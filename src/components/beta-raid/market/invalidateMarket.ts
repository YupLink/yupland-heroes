// Правка витрины админом должна доехать до игрока без перезагрузки.
//
// Живой поток (publishRaid → useRaidLiveStream) снимает окно постройки у тех,
// у кого оно ОТКРЫТО. У самого админа оно в этот момент закрыто: редактор
// маркета живёт в панели клетки (режим бога) и в редакторе карт. Его же
// собственный запрос витрины остаётся в суточном кэше localStorage, и при
// следующем открытии лавки он первым делом рисует прежнюю цену — ровно то
// «в настройках новая, а по факту старая», на которое жаловался владелец.
import type { QueryClient } from "@tanstack/react-query";

/** Снять и список админа, и витрину игрока по этой клетке. */
export function invalidateMarketCell(qc: QueryClient, q: number, r: number): void {
  // Список админа сейчас на экране — обычной инвалидации достаточно.
  void qc.invalidateQueries({ queryKey: ["market-items", q, r] });
  // А витрина покупателя лежит в неактивном запросе: refetchType "all"
  // перечитывает и его, иначе кэш отдаст старую цену ещё раз.
  void qc.invalidateQueries({ queryKey: ["beta-raid-building", q, r], refetchType: "all" });
}
