// Числа маркета: как их читать человеку и как разбирать из поля ввода.
//
// Дробным в маркете бывает ЦЕНА (0,1 золота за молоко), а количество в сделке —
// всегда целое. Обе задачи упираются в одно и то же место: десятичный
// разделитель. Русский пишет и читает запятую, англичанин — точку.
import { useAppStore, type Lang } from "@/lib/store";

/** Дробное — по локали, целое — как было. Три знака режут хвост 0.30000000000000004. */
export const numTextIn = (n: number, lang: Lang): string =>
  n.toLocaleString(lang === "en" ? "en-US" : "ru-RU", { maximumFractionDigits: 3 });

/**
 * Число в витрине — языком ИГРОКА.
 *
 * Язык берём у стора напрямую, а не хуком: подпись цены собирают чистые функции
 * (priceLabel), у которых на руках только `t`. Перерисовку это не ломает —
 * компонент рядом всё равно подписан на язык через useT(), и на смене языка
 * getState() вернёт уже новый.
 */
export const numText = (n: number): string => numTextIn(n, useAppStore.getState().lang);

/** Админка маркета русская целиком — там локаль фиксирована. */
export const numTextRu = (n: number): string => numTextIn(n, "ru");

/**
 * Минус в начале строки — ASCII-дефис ИЛИ типографский «−» (U+2212).
 *
 * Второй прилетает не из воздуха: часть мобильных клавиатур (и любая вставка
 * из редактора с умной типографикой) подставляет именно его. Проверка по
 * ASCII-дефису такой знак не видела, и «−0,2» в поле «пополнить» читалось как
 * «+0,2» — админ нажимал «Убавить», а запас РОС.
 */
const MINUS_RE = /^[-−]/;

/** Что поле разрешает набрать: доли и/или знак минус. */
export type NumMode = {
  /** Штуки, а не доли: дробная часть отбрасывается. */
  integer?: boolean;
  /** Разрешить минус (поле «пополнить» им же и убавляет запас). */
  signed?: boolean;
};

/**
 * Оставить в набранном тексте только число: цифры и ОДИН разделитель.
 *
 * Целому полю разделитель не нужен вовсе — и просто выкинуть запятую нельзя:
 * «1,5» превратилось бы в пятнадцать. Режем по первому разделителю, дробная
 * часть в поле штук отбрасывается.
 *
 * Минус — только ведущий и только там, где его ждут: в поле цены он не значит
 * ничего, а в поле запаса это «убавить».
 */
export function cleanNumText(raw: string, mode?: NumMode): string {
  // Знак ловим ДО чистки: сама чистка выкидывает всё, кроме цифр и запятой,
  // и минус с ним. Одинокий «−» оставляем — человек его только начал набирать.
  const sign = mode?.signed && MINUS_RE.test(raw.trimStart()) ? "-" : "";
  const kept = raw.replace(/[^\d.,]/g, "");
  const [head, ...rest] = kept.split(/[.,]/);
  if (mode?.integer || rest.length === 0) return `${sign}${head}`;
  // Разделитель сохраняем ТОТ, который человек набрал: точку на десктопе не
  // подменяем запятой посреди ввода.
  const sep = kept[head.length] ?? ",";
  return `${sign}${head}${sep}${rest.join("")}`;
}

/**
 * Разбор суммы, введённой руками.
 *
 * На андроид-клавиатуре десятичный разделитель — ЗАПЯТАЯ, а Number("0,1") =
 * NaN. Прежние поля считали сумму как `Number(e.target.value) || 0`, и цена
 * «0,1» либо уезжала нулём (кнопка «Сохранить» гасла), либо оставалась
 * прежней — владелец видел в поле 0,1, а магазин торговал по единице.
 *
 * Пусто → null: у запаса это «без лимита», у цены — «ещё не ввели».
 */
export function parseNum(raw: string): number | null {
  // Типографский минус меняем на ASCII по той же причине, что запятую на точку:
  // Number("−1") — это NaN, а человек набрал минус единицу.
  const s = raw.replace("−", "-").replace(",", ".").trim();
  if (s === "") return null;
  const n = Number(s);
  return Number.isFinite(n) ? n : null;
}
