// Очередь загрузки картинок карты.
//
// На карте до двух сотен разных объектов, декораций и построек, и все их
// адреса появляются разом — карта приходит одним ответом. Браузер честно
// пускал все запросы сразу, а на том конце один процесс, который каждую
// картинку ещё и ужимает под нужный размер. Замер на боевой карте: 158
// запросов, у 149 время ответа больше трёх секунд, у самого невезучего —
// 18,5 с. Весит при этом всё вместе 800 КБ, то есть дело не в трафике, а в
// том, что двести задач пришли одновременно.
//
// Очередь пропускает по несколько штук за раз. Суммарно выходит быстрее:
// сервер отдаёт каждую за десятые доли секунды вместо десятков секунд, а
// картинки появляются постепенно, а не все через полминуты.
//
// Второй заход и так мгновенный — ответы кэшируются на год (api/img ставит
// immutable), поэтому очередь важна ровно для первого показа карты.

/** Сколько картинок грузим одновременно. Больше — снова очередь на сервере. */
const PARALLEL = 6;

type Job = { img: HTMLImageElement; url: string };

const waiting: Job[] = [];
let running = 0;

function pump(): void {
  while (running < PARALLEL && waiting.length > 0) {
    const job = waiting.shift();
    if (!job) break;
    running++;
    const done = () => {
      running--;
      pump();
    };
    // Считаем задачу закрытой и по ошибке: битая картинка не должна занимать
    // место в очереди и держать остальные.
    job.img.addEventListener("load", done, { once: true });
    job.img.addEventListener("error", done, { once: true });
    job.img.src = job.url;
  }
}

/**
 * Поставить картинку в очередь. Адрес присваивается не сразу, поэтому
 * обработчик onload вешать нужно ДО вызова — как и раньше.
 */
export function queueImage(img: HTMLImageElement, url: string): void {
  waiting.push({ img, url });
  pump();
}

/** Сколько картинок ещё в пути или в очереди — заставка ждёт нуля (useScreenSettled). */
export function imagesInFlight(): number {
  return running + waiting.length;
}
