// С каких клеток подходят к цели.
//
// Все шесть соседей, кроме дверей: игрок тапнул по сундуку, а не собирался
// платить за проход. Если других подходов нет вовсе, возвращаем полный набор —
// иначе объект у самой двери стал бы недосягаемым, а платить всё равно
// придётся осознанно (шаг в дверь спросит цену в её окне).
import { DIRS } from "./hexPassable";

export function approachesOf(
  q: number,
  r: number,
  doors: ReadonlySet<string> | undefined,
  /**
   * Вода ли клетка. Задан — к водной цели подходим ТОЛЬКО с воды: сундук или
   * босс посреди моря брались с берега, потому что маршрут выбирал ближайший
   * подход, а им оказывался песок. Правило владельца: на воде — только с судна.
   */
  isWater?: (q: number, r: number) => boolean,
): Array<{ q: number; r: number }> {
  const all = DIRS.map((d) => ({ q: q + d.q, r: r + d.r }));
  // Шесть проверок на тап — дешевле любого поиска, и они же отсекают заведомо
  // ненужные цели: A* дальше перебирает меньше.
  const sea = isWater?.(q, r) ? all.filter((c) => isWater(c.q, c.r)) : all;
  // Пусто быть не должно (изолированных луж с объектами на карте нет), но если
  // такая появится — пусть цель останется досягаемой, а не выпадет из игры.
  const base = sea.length > 0 ? sea : all;
  if (!doors || doors.size === 0) return base;
  const free = base.filter((c) => !doors.has(`${c.q},${c.r}`));
  return free.length > 0 ? free : base;
}
