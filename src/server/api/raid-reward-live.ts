// Срок награды в очереди raid_reward (миграция chest-03).
//
// Правило владельца (28.09.2026): добыча разграбленного магического сундука
// ждёт победителя 24 часа, не забрал — сгорает безвозвратно. Сгоревшую
// награду не показывают и не выдают НИГДЕ: сводка «Добычи», «Забрать» по типу
// и «Забрать все», счётчики и админские отчёты. Поэтому условие одно на всех
// и живёт здесь: своя копия в одном из читателей разъехалась бы, и сгоревшее
// всплыло бы там цифрой или, хуже, выдачей. NULL — бессрочная (все прежние).

/** «Награда ещё жива» для WHERE. alias — имя таблицы в запросе, если есть. */
export function liveRewardSql(alias?: string): string {
  const col = alias ? `${alias}.expires_at` : "expires_at";
  return `(${col} IS NULL OR ${col} > now())`;
}

/**
 * Происхождение награды (ПРАВИЛА §8.18) — с какой меткой свой товар ляжет в
 * рюкзак. Явная колонка origin (origin-02: бой — 'mob', объект карты, декор,
 * грабёж — 'loot'); без неё — как раньше по строке: mob = true — 'mob',
 * mob = false — без метки (сам сундук из «Добычи» — он куплен), иначе по
 * boss_id: шаблон босса — 'mob', прочее — 'loot'. Очередь — всегда добыча
 * (пишут её только бой, объекты, декор и захват сундука), покупок в ней нет,
 * поэтому старая строка без метки — «собрано», а не «безымянное». NULL — без
 * метки. table — имя таблицы наград в запросе (рядом подзапрос шаблонов).
 */
export function rewardOriginSql(table: string): string {
  return `COALESCE(${table}.origin, CASE WHEN ${table}.mob THEN 'mob'
                                         WHEN NOT ${table}.mob THEN NULL
                                         WHEN EXISTS (SELECT 1 FROM yuplink.raid_boss_template bt
                                                       WHERE bt.id = ${table}.boss_id) THEN 'mob'
                                         ELSE 'loot' END)`;
}
