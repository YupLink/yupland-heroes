// Магазина билетов больше нет (владелец, 20.10.2026, ПРАВИЛА §8.61): в игре
// золото, продавать билеты нельзя. Все ручки покупки и догона оплат билетов
// отказывают одной фразой; клиент переводит её словарём (humanError →
// err.tickets_gone). Модуль без серверных импортов: его тянут файлы ручек,
// которые импортирует и клиент.

export const TICKETS_GONE = "Билетов больше нет — в игре золото";

/** Отказ покупки билетов. Бросает всегда; void — чтобы не менять типы ответов ручек. */
export function refuseTicketPurchase(): void {
  throw new Error(TICKETS_GONE);
}
