// SQL-куски про КЛЕТКУ: вода ли она и почём на неё шаг.
//
// Отдельный модуль, потому что читают их трое: причалы и сход на берег
// (ships.ts), цена обычного шага (helpers.getMoveCost) и сводка по целевой
// клетке (step-facts.ts). Скопируй правило ещё раз — и цена на кнопке
// разъедется со списанной, а это ровно тот баг, ради которого правило
// когда-то свели в одно место.

/**
 * Как узнаём воду — по названию типа местности. Хрупко: переименуют «Воду» в
 * «Лазурь» — верфи перестанут находить, куда спускать корабль. Зато не требует
 * правки самих типов местности (её отдельная задача).
 *
 * Таблица шаблонов в запросе обязана называться `t`.
 */
// «ocean» тоже здесь: океан обязан быть ПОДМНОЖЕСТВОМ воды (OCEAN_SQL ниже),
// иначе клетка «Ocean» не считалась бы водой и пускала бы пешком.
export const WATER_SQL = `(t.name ~* '(вод|water|море|океан|ocean|river|река)')`;

/**
 * Океан — ГЛУБОКАЯ вода: тоже вода (WATER_SQL ловит «океан»), но обычному
 * кораблю туда нельзя, ходит только большой. Тот же признак живёт в JS
 * (shipRules.isOceanName). Таблица шаблонов обязана называться `t`.
 */
export const OCEAN_SQL = `(t.name ~* '(океан|ocean)')`;

/**
 * Цена шага на клетку прямо в запросе — та же формула, что у
 * helpers.cellMoveCost: дорога приоритетнее местности, из списка дорог берётся
 * первая `road_*`, а если ни дороги, ни местности нет — шаг стоит единицу.
 *
 * Раньше цену соседей считали шестью отдельными вызовами cellMoveCost, то есть
 * шестью походами в базу на один вопрос «куда сойти». Дублировать правило в SQL
 * неприятно, но выбор между дублем и шестью рейсами по 100 мс — уже не выбор;
 * сверено на живой карте: 16 385 клеток, 30 разных пар дорога/местность, ноль
 * расхождений с cellMoveCost.
 *
 * Таблица клеток в запросе обязана называться `c`.
 */
export const CELL_COST_JOIN = `LEFT JOIN LATERAL (
         SELECT btrim(p.v) AS id
           FROM unnest(string_to_array(COALESCE(c.road_id, ''), ',')) WITH ORDINALITY AS p(v, ord)
          WHERE btrim(p.v) <> ''
          ORDER BY (left(btrim(p.v), 5) = 'road_') DESC, p.ord
          LIMIT 1
       ) rd ON true
       LEFT JOIN yuplink.mystic_item_template tpl ON tpl.id = COALESCE(rd.id, c.terrain_id)`;

/** Само число: 0 и «шаблона нет» одинаково значат единицу. */
export const CELL_COST_SQL = `COALESCE(NULLIF(tpl.stat_amount, 0), 1)`;

/**
 * Держит ли декор клетку: только пока ЕСТЬ его шаблон и тот не объявлен
 * проходимым (meta.walkable=true — таблички, знаки, коврики).
 *
 * Раньше стеной был сам факт `decoration_id IS NOT NULL`. Удалили шаблон —
 * ссылка на клетке осталась, и она запирала проход навсегда: ни имени, ни
 * картинки, ни кнопки — «две мёртвые клетки» (23,39)/(24,39) на «Мире Альфа»
 * (жалоба 20.09). У объектов та же беда давно лечится objectKnownSql; это —
 * тот же ответ для декора. Читают его шаг (step-facts), кружки хода
 * (availableMoves) и вода/берег/спасение (ships.blockedSql): правило одно на
 * всех, иначе пешком пустит, а сойти с борта на ту же клетку — нет.
 *
 * Таблица клеток в запросе обязана называться `c` (или передайте алиас).
 */
export const decorBlocksSql = (c = "c") => `(${c}.decoration_id IS NOT NULL
   AND EXISTS (SELECT 1 FROM yuplink.mystic_item_template dk
                WHERE dk.id = ${c}.decoration_id
                  AND COALESCE(dk.meta->>'walkable', '') <> 'true'))`;

/**
 * Клетка занята ЗДАНИЕМ: постройка на ней самой или клетка — часть большого
 * здания (блок клеток из режима бога, постройка стоит на одной клетке блока,
 * а картинка накрывает все). На здание ничего не ставят и под ним не копают
 * (владелец, 03.10.2026: «на здании не было возможности ставить сундуки… копать
 * под зданиями тоже нельзя»). Таблица клеток — `c` (или передайте алиас).
 */
export const buildingHeldSql = (c = "c") => `(${c}.building_id IS NOT NULL
   OR (${c}.group_id IS NOT NULL
       AND EXISTS (SELECT 1 FROM yuplink.raid_map_cells bb
                    WHERE bb.map_id = ${c}.map_id AND bb.group_id = ${c}.group_id
                      AND bb.building_id IS NOT NULL)))`;
