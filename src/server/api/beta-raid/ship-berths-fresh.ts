// Годится ли кэшированный снимок причалов ЭТОМУ игроку.
//
// Причалы карты с 20.09 отдаются из кэша на 2 с (ship-berths.ts), и снимок
// там бывает снят ДО собственного гребка игрока. Свои же события «ships» автору
// по потоку не приходят (routes/api.beta-raid.events.ts), поэтому после
// морского маршрута клиент сверялся с сервером одним рефетчем — и получал
// судно на ПРОШЛОЙ клетке с собой в экипаже. На экране это выглядело так:
// фигурка героя стоит на воде «пешком», корабль позади него «Занят другим
// игроком», плыть дальше нельзя до F5 (жалоба игрока, 20.09).
//
// Живая правда о своём судне у сервера уже есть — myShip читает базу без
// кэша. Сверяем с ней снимок: если он не знает, где я сижу (или что я уже
// сошёл), снимок протух — его надо выбросить и перечитать. Проверка чистая,
// без базы: ей достаточно клеток снимка и живой записи экипажа.

/** Клетка причала: где и кто там записан капитаном. */
export type SeatCell = { q: number; r: number; crew: readonly string[] };

/**
 * Живая запись «где я сижу»: null — ни на каком судне. Третьего значения «не
 * знаем» здесь нет нарочно: сбой чтения своего судна — это ошибка запроса
 * причалов (ship-action), а не повод отдать снимок, снятый до моего хода.
 */
export type MySeat = { q: number; r: number } | null;

/**
 * true — снимок согласен с живой записью экипажа игрока, отдавать можно.
 * false — снимок снят до моей посадки/гребка/схода, его надо перечитать.
 */
export function knowsMyShip(
  cells: readonly SeatCell[],
  account: string | null,
  my: MySeat,
): boolean {
  if (!account) return true;
  const mine = cells.filter((c) => c.crew.includes(account));
  if (my === null) return mine.length === 0;
  // Ищем именно клетку живой записи, а не первую попавшуюся с моим именем:
  // две записи экипажа на один аккаунт (старые данные, кисть админа) иначе
  // роняли бы снимок на каждом опросе.
  return mine.some((c) => c.q === my.q && c.r === my.r);
}
