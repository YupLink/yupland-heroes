// Количество в одной сделке маркета — всегда ЦЕЛОЕ, для любого вида товара.
//
// Дробным в маркете бывает цена: «1 молоко за 0,1 золота». Дробить сам товар
// незачем и нечем — пол-пака, полгероя и полмолока выдать некуда, а десятые в
// корзине только множили цену на 0,1 и превращали сделку в «0,1 молока за 0,1
// золота».
//
// Проверка серверная и последняя: клиентский степпер шагает целыми, но запрос
// можно послать и мимо него.

/** Кап на сделку — тот же, что в input-схемах покупки и продажи. */
export const QTY_CAP = 99;

/**
 * Привести присланное количество к допустимому. Дробное — ошибка, а не тихое
 * округление: иначе игрок платил бы за 1,5 пака и получал один. Правило одно
 * для всех видов товара, поэтому kind функции и не нужен.
 */
export function normalizeQty(qty: number): number {
  if (!Number.isFinite(qty) || qty <= 0 || qty > QTY_CAP) throw new Error("market.bad_qty");
  if (!Number.isInteger(qty)) throw new Error("market.bad_qty");
  return qty;
}
