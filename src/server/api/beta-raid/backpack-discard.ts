// «Выбросить» из рюкзака: точность остатка.
//
// Дробные остатки задуманы — награды делятся дробно, и в рюкзаке лежат
// 0,000454 Газировки. Раньше количество резалось до тысячных: 0,000178
// превращалось в ноль, UPDATE «count − 0» проходил, игрок видел «выброшено»,
// а стопка оставалась (жалоба 27.09.2026). Теперь списываем ровно присланное.
//
// Число с клиента — double, в базе — numeric: «Всё» из окна отличается от
// лежащего шумом в 16-м знаке, а «Ячейку» у стека 27,738… оставляла бы
// 20,0000000000000018 — две ячейки вместо одной. Поэтому остаток округляется
// до DISCARD_SCALE знаков, и всё, что после этого не больше нуля, — выброс
// стека целиком. Мельче миллиардной товара не бывает, бывает только шум.
//
// С 29.09.2026 (дополнение №4 владельца) выброшенное не пропадает, а падает
// мешочком на клетке героя — сам выброс живёт в loot-bag/bag-discard*.ts.

/** Знаков у остатка после выброса: мельче — шум double↔numeric, а не товар. */
export const DISCARD_SCALE = 9;
