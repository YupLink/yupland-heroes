// То же правило «монетка или сундук», только в терминах SQL.
//
// Три запроса раздачи спрашивают об одном и том же (какие шаблоны брать, кого
// считать убитым, кого снимать с карты) — и до этого модуля спрашивали
// по-разному: два кастовали `(meta->>'maxHp')::numeric` в лоб, третий проверял
// тип. Разница вылезала не в цифрах, а падением: вписанное руками «1 000»
// роняет приведение типа и вместе с ним весь оператор.
//
// Тем же порядком сюда переехал и вопрос «кто стоит на клетке» (cellGroup):
// предпросмотр считал убитых по виду шаблона, а снятие — по префиксу
// object_id, и объект с УДАЛЁННЫМ шаблоном попадал в счёт мимо кассы: в
// обещание «снимем N» не входил, а сносился вместе со всеми.
//
// Числа общие с клиентом (lib/raid/pileKind) — там же разбор на JS.
import { COIN_MAX_HP, DEFAULT_MAX_HP } from "@/lib/raid/pileKind";
import type { ScatterGroup } from "@/lib/raid/scatterPlan";

/**
 * Запас HP шаблона числом; NULL — «поле не заполнено или в нём не число».
 *
 * Проверка типа обязательна: без неё «1 000» в meta роняет весь запрос, а
 * запросы тут массовые — падает не одна строка, а вся раскладка.
 *
 * `alias` — как названа таблица шаблонов в запросе.
 */
export const tplMaxHp = (alias = "t"): string => `CASE
      WHEN jsonb_typeof(${alias}.meta->'maxHp') = 'number' THEN (${alias}.meta->>'maxHp')::numeric
      WHEN COALESCE(${alias}.meta->>'maxHp', '') ~ '^[0-9]+(\\.[0-9]+)?$'
        THEN (${alias}.meta->>'maxHp')::numeric
      END`;

/**
 * Монетка: забирается одним касанием. Незаполненный запас читаем как сундук —
 * тем же числом, что и клиент (DEFAULT_MAX_HP).
 *
 * Через COALESCE, а не голым сравнением: `NULL <= 1` даёт NULL, и `NOT (…)`
 * тоже NULL — шаблон без запаса не попал бы ни в монетки, ни в сундуки.
 */
export const tplIsCoin = (alias = "t"): string =>
  `COALESCE(${tplMaxHp(alias)}, ${DEFAULT_MAX_HP}) <= ${COIN_MAX_HP}`;

/**
 * Монетка ли лежит НА КЛЕТКЕ: тот же вопрос, но об объекте карты, а не о
 * строке справочника. Шаблона в справочнике нет — ответ «нет», и объект
 * уходит к сундукам: туда же, куда правило кладёт любой шаблон без запаса.
 */
const cellIsCoin = (alias: string): string =>
  `EXISTS (SELECT 1 FROM yuplink.mystic_item_template t
                WHERE t.id = split_part(${alias}.object_id, ':', 2) AND ${tplIsCoin("t")})`;

/**
 * КТО стоит на клетке — одним выражением на всех, кто про это спрашивает.
 *
 * Решает ПРЕФИКС object_id, а не вид шаблона: раскладка пишет на карту
 * `boss:` / `chest:` / `artifact:`, и снимает объект та группа, чьим префиксом
 * он подписан. Внутри `chest:` монетку от сундука отличает запас HP шаблона
 * (tplIsCoin) — вид записи у них общий.
 *
 * Шаблон могли удалить из справочника. Такой объект — «чёрная точка» на карте:
 * вскрывать нечего, награды нет. Он идёт в свою префиксную группу и снимается
 * вместе со всеми (в `chest:` — как сундук, потому что незаполненный запас
 * правило читает сундуком). Разъехавшиеся правила стоили ровно этого:
 * предпросмотр не видел сирот («other»), а снятие их сносило — обещали снять
 * N, снимали N плюс сироты.
 */
export const cellGroup = (alias = "c"): string => `CASE
        WHEN ${alias}.object_id LIKE 'boss:%' THEN 'boss'
        WHEN ${alias}.object_id LIKE 'artifact:%' THEN 'artifact'
        WHEN ${alias}.object_id LIKE 'chest:%'
          THEN CASE WHEN ${cellIsCoin(alias)} THEN 'coin' ELSE 'chest' END
        ELSE 'other' END`;

/**
 * «Клетка принадлежит группе» — тот же CASE, только вопросом.
 *
 * Своего условия здесь нет НАМЕРЕННО: пока предикат собран из cellGroup,
 * разойтись с подсчётом ему нечем. Имя группы — литерал из закрытого набора
 * (ScatterGroup), подставлять его в текст безопасно.
 */
export const cellInGroup = (group: ScatterGroup, alias = "c"): string =>
  `(${cellGroup(alias)}) = '${group}'`;

/**
 * Сирота: кучка или артефакт, чей шаблон из справочника удалили.
 *
 * Считается отдельно ради честности предпросмотра: в числе снимаемых сирота
 * неотличим от обычного сундука, а админ вправе знать, что часть уходящего —
 * не отработавшая добыча игроков, а мусор карты. Боссы сюда не попадают: их
 * шаблоны лежат в другой таблице (raid_boss_template), и «нет строки в
 * mystic_item_template» для них норма, а не сиротство.
 */
export const cellOrphan = (alias = "c"): string =>
  `((${alias}.object_id LIKE 'chest:%' OR ${alias}.object_id LIKE 'artifact:%')
        AND NOT EXISTS (SELECT 1 FROM yuplink.mystic_item_template t
                         WHERE t.id = split_part(${alias}.object_id, ':', 2)))`;
