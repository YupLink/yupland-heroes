// «Разграбить» магический сундук — снято (владелец, 29.09.2026; ПРАВИЛА §8.15,
// четвёртая редакция: «подворовывание» вместо захвата).
//
// Прежде победа над охраной или грабёж без охраны уносили сундук и ВСЮ сеть
// владельца в «Добычу» победителя. Теперь чужой, когда живой охраны нет,
// «Открывает» сундук за энергию (open-pass) и берёт из сети хозяина сколько
// хочет — сундук стоит на месте и остаётся в сети; или «Забирает сундук»
// (chest-pickup): сундук открепляется от сети, а если он у хозяина последний —
// вся сеть уходит забравшему. Автоматического захвата на добивающем ударе
// нет (mine-guard-attack снимает мёртвую охрану, как у шахты).
//
// Ручку оставляем ради вкладок прежней версии: они ещё зовут её с кнопки
// «Разграбить» — отказ ключом, игрок прочтёт «открой сундук».
import { createServerFn } from "@tanstack/react-start";
import { z } from "zod";

export const seizeChest = createServerFn({ method: "POST" })
  .inputValidator((d: unknown) => z.object({ q: z.number().int(), r: z.number().int() }).parse(d))
  .handler(async (): Promise<never> => {
    throw new Error("chest.no_plunder");
  });
