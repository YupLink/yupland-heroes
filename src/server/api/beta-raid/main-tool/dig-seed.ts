// Бросок находки лопатой (ПРАВИЛА §8.24 п. 6б) — случайный, на сервере.
//
// От ключа нажатия бросать нельзя: ключ выбирает браузер. Даже HMAC с секретом
// сервера (как у рыбалки) не спасает — ключ нажатия стирает сборщик через двое
// суток, и «кладовый» ключ, присланный снова, бросил бы тот же клад (критик
// 31.10). Повтору нажатия бросок и не нужен: находка лежит в самом ключе
// (`parts.item`), повтор и дубль берут её оттуда.
/** Бросок 0…999 (промилле); перекос от остатка — меньше 1e-6. */
export function digRoll(): number {
  return globalThis.crypto.getRandomValues(new Uint32Array(1))[0] % 1000;
}
