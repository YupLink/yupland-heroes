// Разбор колонки raid_map_cells.road_id — ЕДИНСТВЕННОЕ место, где это делается.
//
// Дорога на клетке ОДНА. Раньше кисть гекс-редактора дописывала новую дорогу к
// уже лежащим и склеивала массив запятой, поэтому на боевой карте слежались
// склейки «id,id,id» — до семи штук на клетку. Игра брала из них первый id,
// редактор рисовал последний: отсюда и «в админке одно, в проде другое».
//
// Слои эту разницу не лечили, а прятали: верхняя дорога закрывала нижние на
// всех 86 клетках с дорогой (силуэт ленты один и тот же, картинки
// непрозрачные) — ни одного видимого пикселя за всю сложность. Поэтому дорога
// снова одна, а кисть её ЗАМЕНЯЕТ.

/**
 * Дорога клетки. Из старой склейки берём ПОСЛЕДНИЙ id — это последний мазок
 * админа, и ровно его редактор рисовал сверху, когда карту рисовали. Так что
 * прод теперь показывает то же, что админ видел в редакторе.
 *
 * Мусорные части (легаси-«path» с ранних черновиков) НЕ выбрасываем: под них
 * тоже заведён шаблон с ценой шага, и молчаливое расхождение цены на кнопке со
 * списанной энергией дороже красивого фильтра.
 *
 * Расхождение с SQL цены шага (cell-sql.CELL_COST_JOIN берёт из склейки ПЕРВУЮ
 * `road_*`) остаётся ровно до миграции склеек: на клетке с одной дорогой первый
 * и последний id — один и тот же, и расходиться нечему по построению.
 */
export function cellRoadId(raw: string | null | undefined): string | null {
  if (!raw) return null;
  const parts = raw.split(",");
  for (let i = parts.length - 1; i >= 0; i--) {
    const id = parts[i].trim();
    if (id) return id;
  }
  return null;
}

/**
 * Что писать в колонку road_id по присланному от админа: `roadId` — дорога или
 * `null` («снять»). `undefined` — «дорогу не трогаем» (правка прислана без неё).
 *
 * Через тот же разбор, что и чтение: пришли к нам склейкой (старый клиент,
 * выгрузка черновика, набранного до этой правки) — в базу ляжет одна дорога.
 */
export function roadColumn(input: { roadId?: string | null }): string | null | undefined {
  if (input.roadId === undefined) return undefined;
  return cellRoadId(input.roadId);
}
