// Страница по курсору «at < cursor» для ленты и сделок.
//
// Курсор — только время, без id (у ленты UNION из семи таблиц, общего id
// нет). Опасное место — граница страницы: суточные строки энергии и сделки
// одной операции делят одно «at», и если лимит режет их посередине, хвост с
// тем же временем на следующей странице уже не покажется (at < cursor их
// отбросит). Поэтому полная страница отдаётся без «пограничного» времени:
// строки с at последней строки снимаются целиком, курсор — время последней
// оставшейся, и следующая страница начнётся ровно с них. Когда вся страница
// — одно время (сотни строк в одну миллисекунду), резать нечего: отдаём как
// есть, хвост того же времени теряется — это осознанный предел.
export type PagedByAt<T> = { rows: T[]; nextCursor: string | null };

/**
 * page — выборка с лимитом limit + 1: лишняя строка говорит «есть ещё» и
 * задаёт пограничное время, которое целиком уезжает на следующую страницу.
 */
export function pageByAt<T extends { at: string }>(page: T[], limit: number): PagedByAt<T> {
  if (page.length <= limit) return { rows: page, nextCursor: null };
  const edge = page[limit].at;
  const kept = page.slice(0, limit).filter((r) => r.at !== edge);
  if (kept.length === 0) return { rows: page.slice(0, limit), nextCursor: edge };
  return { rows: kept, nextCursor: kept[kept.length - 1].at };
}
