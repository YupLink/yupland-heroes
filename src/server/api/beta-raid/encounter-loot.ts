// Сундук, монетка и артефакт забираются платой за подход, а не боем.
//
// Правило владельца: «хоть у них и есть HP, собираться должны без боя —
// списалась энергия, награда отдалась». Раньше запас HP у сундука означал,
// что его надо выбивать отрядом: игрок без фишек платил энергию, наносил ноль
// урона и уходил ни с чем, а сундук так и стоял полным.
//
// HP у сундука при этом не бутафория: по нему считается, монетка это или
// полноценный тайник (maxHp = 1 — монетка), и он же остаётся мерой того,
// «опустошён ли объект» для всей остальной механики. Поэтому не выкидываем
// его, а закрываем разом — как будто подошедший забрал содержимое целиком.
import type { SimResult } from "./encounter-sim-types";

/** Виды, которые открываются платой за подход, без отряда и без урона. */
export function opensWithoutFight(kind: string): boolean {
  return kind === "chest" || kind === "artifact";
}

/**
 * «Бой», которого не было: весь запас HP снимается сразу, раундов ноль.
 *
 * Возвращаем ту же форму, что и симуляция, — дальше по коду ничего менять не
 * нужно: запись урона, добивание и выдача награды работают как обычно.
 */
export function instantLoot(currentHp: number): SimResult {
  return {
    dealt: Math.max(1, Math.ceil(currentHp)),
    rounds: 0,
    wiped: false,
    log: [],
    abilities: [],
    side: { chipEffects: [], burnedEnergy: 0, slow: null, weaken: {} },
  };
}
